// Builds the index pages of the records when the documentation site is built.
//
// A decision record lives in a file of its own. An index committed beside the records was a table that every
// pull request adding a record edited, so two such pull requests always
// conflicted. These pages are built from the files instead, and never
// committed: docs/.gitignore ignores src/content/docs/records/.
//
// astro.config.mjs calls writeRecordPages() before the site is built, and
// `node docs/scripts/records.mjs` writes the same pages alone.
//
//   records/decisions        docs/decisions, from each record's front matter:
//                            id, title, status, date, supersedes and amends.
//                            "superseded by" and "amended by" are computed from
//                            the newer records, so an old record is never edited
//
// internal/arch/record_ids_test.go checks the front matter these pages read.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import yaml from 'js-yaml';

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(here, '..');
const outDir = join(docsRoot, 'src/content/docs/records');

// A page under records/ is four folders below docs/, so a link to a record
// climbs four. The site does not publish the records themselves; the link
// opens the file in the vault and on GitHub.
const UP = '../../../../';

const DATED = /^(\d{8}-[a-hjkmnp-tv-z2-7]{3})-/;

const GENERATOR = 'docs/scripts/records.mjs';

function frontMatter(file) {
  const body = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const found = /^---\n([\s\S]*?)\n---\n/.exec(body);

  if (!found) return { meta: {}, body };

  // JSON_SCHEMA reads 2026-10-25 as text, which is how the records write it.
  return { meta: yaml.load(found[1], { schema: yaml.JSON_SCHEMA }) || {}, body: body.slice(found[0].length) };
}

function markdownIn(dir) {
  return readdirSync(join(docsRoot, dir))
    .filter((name) => name.endsWith('.md'))
    .sort();
}

function cell(value) {
  return String(value ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

function list(value) {
  if (Array.isArray(value)) return value.map(String);
  if (value === undefined || value === null || value === '') return [];

  return [String(value)];
}

function page(title, description, source, intro, table) {
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    'audience: build',
    'rewrite:',
    '  describes: current',
    '  implementedBy:',
    `    - ${GENERATOR}`,
    '---',
    '',
    `Generated by ${GENERATOR} from ${source} when the site is built. Do not edit: change the files it reads.`,
    '',
    intro,
    '',
    table,
    '',
  ].join('\n');
}

// ── decisions ───────────────────────────────────────────────────────────────

function decisionID(name) {
  const dated = DATED.exec(name);

  return dated ? dated[1] : null;
}

export function readDecisions() {
  const records = [];

  for (const name of markdownIn('decisions')) {
    const id = decisionID(name);
    if (!id) continue;

    const { meta } = frontMatter(join(docsRoot, 'decisions', name));
    const ref = `ADR-${id}`;

    records.push({
      ref,
      name,
      title: String(meta.title ?? '').replace(new RegExp(`^${ref}:\\s*`), ''),
      status: String(meta.status ?? ''),
      date: String(meta.date ?? ''),
      supersedes: list(meta.supersedes),
      amends: list(meta.amends),
      supersededBy: [],
      amendedBy: [],
    });
  }

  const byRef = new Map(records.map((record) => [record.ref, record]));

  for (const record of records) {
    for (const ref of record.supersedes) byRef.get(ref)?.supersededBy.push(record.ref);
    for (const ref of record.amends) byRef.get(ref)?.amendedBy.push(record.ref);
  }

  return records;
}

function decisionsPage() {
  const records = readDecisions();
  const link = (ref) => {
    const record = records.find((r) => r.ref === ref);

    return record ? `[${ref}](${UP}decisions/${record.name})` : ref;
  };

  const rows = records.map((record) => {
    const changes = [
      ...record.supersedes.map((ref) => `supersedes ${link(ref)}`),
      ...record.amends.map((ref) => `amends ${link(ref)}`),
    ];
    const changedBy = [
      ...record.supersededBy.map((ref) => `superseded by ${link(ref)}`),
      ...record.amendedBy.map((ref) => `amended by ${link(ref)}`),
    ];
    const status = record.supersededBy.length > 0 ? `${record.status}, superseded` : record.status;

    return `| ${link(record.ref)} | ${cell(record.title)} | ${cell(status)} | ${cell(record.date)} | ${changes.join(', ')} | ${changedBy.join(', ')} |`;
  });

  const intro = [
    'Every decision record in `docs/decisions/`, in the order of its id. A record that replaces or',
    'changes an older one names it in its own front matter, under `supersedes` or `amends`. The',
    'last column is computed from those names, so an older record is never edited to say it was',
    'replaced. `make adr-new` writes a new record.',
  ].join('\n');

  const table = [
    '| record | title | status | date | changes | changed by |',
    '|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');

  return page('Decisions', 'Every decision record, with its status and the records that supersede or amend it.', '`docs/decisions/`', intro, table);
}

// ── the run ─────────────────────────────────────────────────────────────────

export function writeRecordPages() {
  mkdirSync(outDir, { recursive: true });

  const pages = {
    'decisions.md': decisionsPage(),
  };

  for (const [name, body] of Object.entries(pages)) {
    const file = join(outDir, name);
    let held = null;

    try {
      held = readFileSync(file, 'utf8');
    } catch {
      held = null;
    }

    // Unchanged bytes are not written again, so the dev server does not reload
    // on every start.
    if (held !== body) writeFileSync(file, body);
  }

  return Object.keys(pages).length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.stdout.write(`records: wrote ${writeRecordPages()} pages to ${outDir}\n`);
}
