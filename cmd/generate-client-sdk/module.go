// Module mode. It reads a module's OpenAPI fragment, rebases the paths under
// /api/v1/modules/<namespace>/ and writes a package that binds the operations
// onto a @prusa/connect client.
//
// The operations file, the rebased document and the manifest's peer range are
// generated and compared under -check. README.md, tsconfig.json and
// src/index.ts are written once and then belong to the author.

const (
	// modulesMount is where the host mounts every module's routes.
	modulesMount = "/api/v1/modules"
	// tokenEnv names the credential a -document URL is fetched with.
	tokenEnv = "PCL_TOKEN"
	// corePackage is the package a module package peers on.
	corePackage = "@prusa/connect"

	moduleTypesFile    = "module-api.ts"
	moduleDocumentName = "openapi.json"
	moduleIndexPath    = "src/index.ts"
	readmeName         = "README.md"
	tsconfigName       = "tsconfig.json"

	// The dev tools the skeleton pins. Keep them at the core package's own
	// versions.
	openapiTypescriptVersion = "7.13.0"
	typescriptVersion        = "6.0.3"

	fetchTimeout = 30 * time.Second

	moduleNotice = "// Generated by 'generate-client-sdk -module' from the OpenAPI fragment of %s.\n" +
		"// Do not edit: change the fragment and regenerate.\n"
)

var (
	errNoNamespace = errors.New("-module takes -namespace, the module's namespace")
	errNoOutDir    = errors.New("-module takes -out, the directory the package is written to")
	errMixedPaths  = errors.New("the document mixes paths under the mount with paths relative to it")
	errNoPeer      = errors.New("package.json declares no peerDependency on " + corePackage)
	errFetch       = errors.New("the document could not be fetched")
)

type moduleInputs struct {
	operations []operation
	// document is the rebased fragment, indented. openapi-typescript renders
	// the types file from it.
	document []byte
	manifest []byte
	version  string
}

func runModule(opts options) error {
	if err := completeModuleOptions(&opts); err != nil {
		return err
	}

	in, err := readModuleInputs(opts)
	if err != nil {
		return err
	}

	generated, scaffold := renderModule(in, opts)

	if opts.check {
		var problems []error

		for _, a := range generated {
			problems = append(problems, codegen.CompareFile(a.path, a.content, errStale, "generate-client-sdk"))
		}

		return errors.Join(problems...)
	}

	for _, a := range generated {
		if err = codegen.WriteFile(a.path, a.content); err != nil {
			return err
		}
	}

	for _, a := range scaffold {
		if _, statErr := os.Stat(a.path); statErr == nil {
			continue
		}

		if err = codegen.WriteFile(a.path, a.content); err != nil {
			return err
		}
	}

	fmt.Fprintf(os.Stderr, "OK module client: %s (%d operations under %s)\n",
		opts.outDir, len(in.operations), mountOf(opts.namespace))

	return nil
}

// completeModuleOptions checks the required flags and fills the defaults.
func completeModuleOptions(opts *options) error {
	opts.namespace = strings.Trim(opts.namespace, "/")
	if opts.namespace == "" || strings.Contains(opts.namespace, "/") {
		return errNoNamespace
	}

	if opts.outDir == "" {
		return errNoOutDir
	}

	if opts.packageName == "" {
		labels := strings.Split(opts.namespace, ".")
		opts.packageName = "prusa-connect-" + labels[len(labels)-1]
	}

	if opts.token == "" {
		opts.token = os.Getenv(tokenEnv)
	}

	return nil
}

func mountOf(namespace string) string {
	return modulesMount + "/" + namespace
}

func readModuleInputs(opts options) (*moduleInputs, error) {
	raw, err := readDocumentSource(opts.documentPath, opts.token)
	if err != nil {
		return nil, err
	}

	rebased, err := rebaseFragment(raw, opts.namespace)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", opts.documentPath, err)
	}

	var doc document
	if err = json.Unmarshal(rebased, &doc); err != nil {
		return nil, fmt.Errorf("decode the rebased document: %w", err)
	}

	ops, err := operationsOf(&doc)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", opts.documentPath, err)
	}

	version := opts.coreVersion
	if version == "" {
		if version, err = readVersion(opts.versionPath); err != nil {
			return nil, err
		}
	}

	manifest, err := readModuleManifest(opts, version)
	if err != nil {
		return nil, err
	}

	return &moduleInputs{operations: ops, document: rebased, manifest: manifest, version: version}, nil
}

// readDocumentSource reads the fragment from a path or fetches it from a URL.
// An empty token sends no Authorization header.
func readDocumentSource(source, token string) ([]byte, error) {
	if !strings.HasPrefix(source, "http://") && !strings.HasPrefix(source, "https://") {
		data, err := os.ReadFile(source)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", source, err)
		}

		return data, nil
	}

	ctx, cancel := context.WithTimeout(context.Background(), fetchTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, source, nil)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", errFetch, err)
	}

	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}

	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", errFetch, err)
	}
	defer resp.Body.Close()

	data, err := io.ReadAll(io.LimitReader(resp.Body, routesapi.MaxFragmentBytes+1))
	if err != nil {
		return nil, fmt.Errorf("%w: read %s: %w", errFetch, source, err)
	}

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%w: %s answered %s. Pass -token or set %s to a credential that reads the module",
			errFetch, source, resp.Status, tokenEnv)
	}

	return data, nil
}

// rebaseFragment accepts paths relative to the mount or already under it. The
// second form is stripped back to the first, so both pass the same checks.
func rebaseFragment(raw []byte, namespace string) ([]byte, error) {
	mount := mountOf(namespace)

	relative, err := stripMount(raw, mount)
	if err != nil {
		return nil, err
	}

	fragment, err := routesapi.ParseFragment(relative)
	if err != nil {
		return nil, err
	}

	rebased, err := fragment.Rebase(mount)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	if err = json.Indent(&out, rebased, "", "  "); err != nil {
		return nil, fmt.Errorf("indent the rebased document: %w", err)
	}

	out.WriteString("\n")

	return out.Bytes(), nil
}

// stripMount removes the mount from every path of a served document. A
// document that mixes both forms is refused.
func stripMount(raw []byte, mount string) ([]byte, error) {
	var members map[string]json.RawMessage
	if err := json.Unmarshal(raw, &members); err != nil {
		return nil, fmt.Errorf("%w: it does not parse as a JSON object: %w", routesapi.ErrFragment, err)
	}

	var paths map[string]json.RawMessage
	if err := json.Unmarshal(members["paths"], &paths); err != nil || len(paths) == 0 {
		return nil, fmt.Errorf("%w: paths is not an object naming at least one path", routesapi.ErrFragment)
	}

	stripped := make(map[string]json.RawMessage, len(paths))
	under := 0

	for path, item := range paths {
		rest, ok := strings.CutPrefix(path, mount+"/")
		if ok {
			under++
			stripped["/"+rest] = item
		} else {
			stripped[path] = item
		}
	}

	switch under {
	case 0:
		return raw, nil
	case len(paths):
	default:
		return nil, fmt.Errorf("%w: %d of %d are under %s", errMixedPaths, under, len(paths), mount)
	}

	rendered, err := json.Marshal(stripped)
	if err != nil {
		return nil, fmt.Errorf("render the stripped paths: %w", err)
	}

	members["paths"] = rendered

	return json.Marshal(members)
}

// readModuleManifest returns the package.json on disk with its peer range
// stamped, or the skeleton when there is none.
func readModuleManifest(opts options, version string) ([]byte, error) {
	path := filepath.Join(opts.outDir, manifestName)

	manifest, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return moduleManifest(opts.packageName, opts.namespace, version), nil
	}

	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	return stampPeer(manifest, version)
}

// stampPeer rewrites the peer range on the core package. The search starts at
// the peer block because devDependencies may name the package too.
func stampPeer(manifest []byte, version string) ([]byte, error) {
	const (
		block = `"peerDependencies"`
		field = `"` + corePackage + `": "`
	)

	start := bytes.Index(manifest, []byte(block))
	if start < 0 {
		return nil, errNoPeer
	}

	offset := bytes.Index(manifest[start:], []byte(field))
	if offset < 0 {
		return nil, errNoPeer
	}

	start += offset + len(field)

	end := bytes.IndexByte(manifest[start:], '"')
	if end < 0 {
		return nil, errNoPeer
	}

	out := make([]byte, 0, len(manifest)+len(version))
	out = append(out, manifest[:start]...)
	out = append(out, version...)
	out = append(out, manifest[start+end:]...)

	return out, nil
}

func renderModule(in *moduleInputs, opts options) (generated, scaffold []artefact) {
	generatedDirPath := filepath.Join(opts.outDir, generatedDir)

	target := operationsTarget{
		notice:      fmt.Sprintf(moduleNotice, opts.namespace),
		runtimeFrom: corePackage,
		typesFrom:   "./" + strings.TrimSuffix(moduleTypesFile, ".ts") + ".js",
		description: "The routes of module " + opts.namespace + ", one method per operation, bound to one transport.",
	}

	generated = []artefact{
		{path: filepath.Join(generatedDirPath, "operations.ts"), content: renderOperationsFor(in.operations, target)},
		{path: filepath.Join(opts.outDir, moduleDocumentName), content: in.document},
		{path: filepath.Join(opts.outDir, manifestName), content: in.manifest},
	}

	scaffold = []artefact{
		{path: filepath.Join(opts.outDir, moduleIndexPath), content: renderModuleIndex(opts.namespace)},
		{path: filepath.Join(opts.outDir, tsconfigName), content: []byte(moduleTsconfig)},
		{path: filepath.Join(opts.outDir, readmeName), content: renderModuleReadme(opts, in.version)},
	}

	return generated, scaffold
}

// moduleManifest is the skeleton package.json.
func moduleManifest(name, namespace, version string) []byte {
	var b bytes.Buffer

	b.WriteString("{\n")
	fmt.Fprintf(&b, "  \"name\": %s,\n", tsString(name))
	b.WriteString("  \"version\": \"0.1.0\",\n")
	fmt.Fprintf(&b, "  \"description\": %s,\n",
		tsString("A typed client for the routes of module "+namespace+
			", generated from its OpenAPI fragment. It binds onto a "+corePackage+" client."))
	b.WriteString("  \"type\": \"module\",\n")
	b.WriteString("  \"sideEffects\": false,\n")
	b.WriteString("  \"exports\": {\n")
	b.WriteString("    \".\": {\n")
	b.WriteString("      \"types\": \"./dist/index.d.ts\",\n")
	b.WriteString("      \"default\": \"./dist/index.js\"\n")
	b.WriteString("    }\n")
	b.WriteString("  },\n")
	b.WriteString("  \"types\": \"./dist/index.d.ts\",\n")
	b.WriteString("  \"files\": [\n    \"dist\",\n    \"README.md\"\n  ],\n")
	b.WriteString("  \"scripts\": {\n")
	b.WriteString("    \"build\": \"tsc -p tsconfig.json\",\n")
	fmt.Fprintf(&b, "    \"generate:types\": \"openapi-typescript %s -o src/generated/%s\"\n",
		moduleDocumentName, moduleTypesFile)
	b.WriteString("  },\n")
	b.WriteString("  \"peerDependencies\": {\n")
	fmt.Fprintf(&b, "    %s: %s\n", tsString(corePackage), tsString(version))
	b.WriteString("  },\n")
	b.WriteString("  \"devDependencies\": {\n")
	fmt.Fprintf(&b, "    \"openapi-typescript\": %s,\n", tsString(openapiTypescriptVersion))
	fmt.Fprintf(&b, "    \"typescript\": %s\n", tsString(typescriptVersion))
	b.WriteString("  },\n")
	b.WriteString("  \"engines\": {\n    \"node\": \">=22.12.0\"\n  }\n")
	b.WriteString("}\n")

	return b.Bytes()
}

// renderModuleIndex writes src/index.ts: bind and the re-exports.
func renderModuleIndex(namespace string) []byte {
	var b bytes.Buffer

	b.WriteString("// The hand-written half of this package. generate-client-sdk -module wrote it\n")
	b.WriteString("// on the first run and leaves it alone: add exports here, and never under\n")
	b.WriteString("// src/generated/.\n\n")
	fmt.Fprintf(&b, "import type { Transport } from %s;\n", tsString(corePackage))
	b.WriteString("import { bindOperations, type Operations } from \"./generated/operations.js\";\n\n")

	b.WriteString("/** What bind takes from a client: the transport that sends its requests. " +
		"A PrusaConnect is one. */\n")
	b.WriteString("export interface Client {\n")
	b.WriteString("  readonly transport: Transport;\n")
	b.WriteString("}\n\n")

	b.WriteString("/**\n")
	fmt.Fprintf(&b, " * bind attaches every operation of module %s to the client's\n", namespace)
	b.WriteString(" * transport. A call carries the client's URL and credential, and a refusal\n")
	b.WriteString(" * is the same ApiError the core's operations throw, with the module's own\n")
	b.WriteString(" * code as a string.\n")
	b.WriteString(" */\n")
	b.WriteString("export function bind(client: Client): Operations {\n")
	b.WriteString("  return bindOperations(client.transport);\n")
	b.WriteString("}\n\n")

	b.WriteString("export { bindOperations, operationTable, type Operations } from \"./generated/operations.js\";\n")
	fmt.Fprintf(&b, "export type { components, operations, paths } from \"./generated/%s\";\n",
		strings.TrimSuffix(moduleTypesFile, ".ts")+".js")

	return b.Bytes()
}

