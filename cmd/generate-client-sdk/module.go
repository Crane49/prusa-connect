// renderModuleReadme writes the module package's README. The first line marks
// it as generated.
func renderModuleReadme(opts options, version string) []byte {
	var b bytes.Buffer

	mount := mountOf(opts.namespace)

	b.WriteString("<!-- Generated by generate-client-sdk -module on the first run. ")
	b.WriteString("src/generated is written by the generator; this page belongs to the author. -->\n")
	fmt.Fprintf(&b, "# %s\n\n", opts.packageName)
	fmt.Fprintf(&b, "A typed client for the routes of module `%s`, generated from the\n", opts.namespace)
	fmt.Fprintf(&b, "module's own OpenAPI fragment. It adds nothing to the wire: every call goes\n")
	fmt.Fprintf(&b, "through a `%s` client's transport, under `%s/`.\n\n", corePackage, mount)

	b.WriteString("## Using it\n\n")
	b.WriteString("```ts\n")
	fmt.Fprintf(&b, "import { PrusaConnect, ApiError } from %s;\n", tsString(corePackage))
	fmt.Fprintf(&b, "import { bind } from %s;\n\n", tsString(opts.packageName))
	b.WriteString("const local = new PrusaConnect({ url: \"https://printers.local:8080\", auth: \"pcl_...\" });\n")
	b.WriteString("const module = bind(local);\n\n")
	b.WriteString("try {\n")
	b.WriteString("  // One method per operation in the fragment, named after its operationId.\n")
	b.WriteString("  await module.someOperation({ path: { id: \"x\" } });\n")
	b.WriteString("} catch (err) {\n")
	b.WriteString("  if (err instanceof ApiError) console.log(err.status, err.code);\n")
	b.WriteString("}\n")
	b.WriteString("```\n\n")
	b.WriteString("`bind` takes anything with a `transport`, and a `PrusaConnect` is one. The\n")
	b.WriteString("methods it returns take the same request object and `AbortSignal` as the\n")
	b.WriteString("core's, and they send the client's credential.\n\n")

	b.WriteString("## Errors and events\n\n")
	b.WriteString("A module's fragment carries no error registry, no event types and no\n")
	b.WriteString("authorization vocabulary, so this package ships none. A refused call throws\n")
	fmt.Fprintf(&b, "the core's `ApiError`, and `err.code` is the module's own code as a string,\n")
	b.WriteString("outside the union the core package names. Events the module publishes are\n")
	b.WriteString("read with the core client's `events()`, by type.\n\n")

	b.WriteString("## Where the code comes from\n\n")
	b.WriteString("| file | written by |\n|---|---|\n")
	fmt.Fprintf(&b, "| `%s` | `generate-client-sdk -module`, the fragment rebased under `%s` |\n",
		moduleDocumentName, mount)
	fmt.Fprintf(&b, "| `src/generated/%s` | `openapi-typescript`, from that document |\n", moduleTypesFile)
	b.WriteString("| `src/generated/operations.ts` | `generate-client-sdk -module` |\n")
	b.WriteString("| `src/index.ts`, this page, `tsconfig.json` | written once by the generator, then yours |\n\n")

	b.WriteString("To regenerate after the fragment changes:\n\n")
	b.WriteString("```sh\n")
	b.WriteString("generate-client-sdk -module -document <the fragment, a path or the host's URL> \\\n")
	fmt.Fprintf(&b, "  -namespace %s -name %s -out <this directory>\n", opts.namespace, opts.packageName)
	b.WriteString("pnpm install\n")
	b.WriteString("pnpm run generate:types && pnpm run build\n")
	b.WriteString("```\n\n")
	b.WriteString("`generate-client-sdk -module -check` with the same flags fails when the\n")
	b.WriteString("committed files differ from what the fragment generates.\n\n")

	fmt.Fprintf(&b, "The peer range on `%s` is `%s`, the version of the core this\n", corePackage, version)
	b.WriteString("package was generated against. The core package's version is the server's,\n")
	b.WriteString("so a consumer installs the one its server runs.\n")

	return b.Bytes()
}
