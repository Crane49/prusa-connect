// Command generate-capabilities writes docs/src/content/docs/capabilities.md,
// the capability vocabulary a driver author declares against. It reads the
// shipped profiles and the closed sets in sdk/connectorapi.
//
// With -check it writes nothing and fails when the committed page differs.
//
// Run via: make generate-capabilities, gated by make capabilities-check.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/internal/printer/profile"
)

const (
	defaultReferencePath = "docs/src/content/docs/capabilities.md"

	// generatedNotice is the first thing in the artefact.
	generatedNotice = "Generated by 'make generate-capabilities' from the profiles this build ships, " +
		"the closed sets in sdk/connectorapi and the host feature table this build declares. " +
		"Do not edit."
)

// errStale means the committed page differs from the generated one.
var errStale = errors.New("committed artefact differs from the profile data")

func main() {
	var (
		referencePath string
		check         bool
	)

	flag.StringVar(&referencePath, "reference", defaultReferencePath,
		"path of the published capability reference")
	flag.BoolVar(&check, "check", false,
		"compare the committed artefact against the generated one and write nothing")
	flag.Parse()

	if err := run(referencePath, check); err != nil {
		fmt.Fprintf(os.Stderr, "generate-capabilities: %v\n", err)
		os.Exit(1)
	}
}

func run(referencePath string, check bool) error {
	registry, err := profile.Builtin()
	if err != nil {
		return fmt.Errorf("load the built-in profiles: %w", err)
	}

	page := renderReference(registry)

	if check {
		return compareFile(referencePath, page)
	}

	if err = os.WriteFile(referencePath, page, codegen.FilePerms); err != nil {
		return fmt.Errorf("write %s: %w", referencePath, err)
	}

	fmt.Fprintf(os.Stderr, "OK capability reference: %s (%d keys, %d profiles)\n",
		referencePath, len(registry.Coverage()), len(registry.Profiles))

	return nil
}

func compareFile(path string, want []byte) error {
	return codegen.CompareFile(path, want, errStale, "generate-capabilities")
}
