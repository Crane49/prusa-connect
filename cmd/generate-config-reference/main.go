// Command generate-config-reference writes the key tables of the configuration
// pages under docs/src/content/docs/config/, one page per entry of
// config.Pages. Paths, types and defaults come from the structs the core
// decodes its file into. The sentence for each key comes from config.Keys and
// resource.Keys.
//
// It replaces only the region between two marker comments on each page. With
// -check it writes nothing and fails when a committed page differs.
//
// Run via: make generate-config-reference, gated by make config-reference-check.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"

	"github.com/prusa3d/prusa-connect/internal/app/config"
	"github.com/prusa3d/prusa-connect/internal/app/resource"
	"github.com/prusa3d/prusa-connect/internal/codegen"
)

const (
	makeTarget = "generate-config-reference"

	defaultReferencePath = "docs/src/content/docs/config.md"

	// The markers on a page. Only the text between them is generated.
	regionStart = "<!-- generated by make " + makeTarget + " for "
	regionEnd   = "<!-- end generated -->"

	regionSubject = "every key the core reads"
	regionFix     = "change the struct and its row in config.Keys or resource.Keys, then regenerate."

	// maxWords is the longest sentence one key may have. A key that needs more
	// gets a paragraph above the table.
	maxWords = 30
)

var (
	// errUndocumented means a key in the structs has no row in the tables.
	errUndocumented = errors.New("a key the core reads has no sentence")
	// errUnknownKey means a row describes a key no struct has.
	errUnknownKey = errors.New("a sentence describes a key the core does not read")
	// errLongSentence means a sentence is over maxWords.
	errLongSentence = errors.New("a key's sentence is too long")
	// errLevel means a wizard level is neither basic nor advanced.
	errLevel = errors.New("a key names a wizard level that does not exist")
	// errSee means a key's See names no page of the site.
	errSee = errors.New("a key names a documentation page that does not exist")
	// errStale means a committed page differs from the generated one.
	errStale = errors.New("committed page differs from the generated one")
)

// pageRegion is the marker pair of a page.
//
//nolint:gochecknoglobals // the marker protocol of one page, read and never written.
var pageRegion = codegen.Region{Start: regionStart, End: regionEnd}

type options struct {
	referencePath string
	check         bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath, "path of the configuration page")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed page against the generated one and write nothing")
	flag.Parse()

	if err := run(opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-config-reference: %v\n", err)
		os.Exit(1)
	}
}

func run(opts options) error {
	blocks := blocks()

	if err := check(blocks); err != nil {
		return err
	}

	if err := checkSee(filepath.Dir(opts.referencePath), config.Keys, resource.Keys); err != nil {
		return err
	}

	var stale []error

	for _, page := range config.Pages {
		path := pagePath(opts.referencePath, page.Slug)

		body, err := renderPage(path, region(rowsOn(blocks, page.Slug)))
		if err != nil {
			return err
		}

		if opts.check {
			if err = codegen.CompareFile(path, body, errStale, makeTarget); err != nil {
				stale = append(stale, err)
			}

			continue
		}

		if err = codegen.WriteFile(path, body); err != nil {
			return err
		}
	}

	if opts.check {
		return errors.Join(stale...)
	}

	fmt.Fprintf(os.Stderr, "OK configuration reference: %d pages under %s (%d keys)\n",
		len(config.Pages), filepath.Dir(pagePath(opts.referencePath, "")), len(pathsOf(blocks)))

	return nil
}

// pagePath returns the file of one page: config/network.md beside config.md.
func pagePath(reference, slug string) string {
	return filepath.Join(filepath.Dir(reference), strings.TrimSuffix(filepath.Base(reference), ".md"), slug+".md")
}

// rowsOn keeps the rows that belong on one page and drops a block with none.
func rowsOn(all []block, slug string) []block {
	var out []block

	for _, one := range all {
		kept := one
		kept.Rows = nil

		for _, each := range one.Rows {
			if config.PageOf(each.Path) == slug {
				kept.Rows = append(kept.Rows, each)
			}
		}

		if len(kept.Rows) > 0 {
			out = append(out, kept)
		}
	}

	return out
}

// blocks returns the three top-level blocks of the configuration file. The
// field core.persistence has the yaml tag "-", so it appears only at top level.
func blocks() []block {
	defaults := config.Default()

	return []block{
		{
			Name: "core",
			Intro: "Every key has a working default, so a file with no `core:` block starts a server. " +
				"A key this build does not read is refused at startup, with the line it is written on.",
			Rows: walk("core", reflect.TypeFor[config.Core](), reflect.ValueOf(defaults), config.Keys),
		},
		{
			Name: "persistence",
			Intro: "The database engine, shared by the permission graph, the device records and the " +
				"command queue. It is at the top level of the file and is refused inside `core:`.",
			Rows: walk("persistence", reflect.TypeFor[config.Persistence](),
				reflect.ValueOf(defaults.Persistence), config.Keys),
		},
		{
			Name: "resources",
			Intro: "One block per declared instance, keyed by kind and then by the name you choose. " +
				"An unknown key inside one is refused at startup.",
			Rows: walk("resources.<kind>."+config.Placeholder, resource.EntryType(), reflect.Value{}, resource.Keys),
		},
	}
}

func check(blocks []block) error {
	return errors.Join(
		checkDocumented(blocks),
		checkUnknown(blocks),
		checkLength(blocks),
		checkLevels(config.Keys, resource.Keys),
	)
}

// checkLevels refuses a level the first-run wizard does not know and a
// DependsOn that names no key of the same table.
func checkLevels(tables ...map[string]config.Key) error {
	var wrong []string

	for _, table := range tables {
		for path, key := range table {
			if key.DependsOn != "" {
				named, _, _ := strings.Cut(key.DependsOn, "=")
				if _, known := table[named]; !known {
					wrong = append(wrong, path+" (depends on "+named+", which is no key)")
				}
			}

			switch key.Level {
			case "", config.LevelBasic, config.LevelAdvanced:
			default:
				wrong = append(wrong, path+" ("+key.Level+")")
			}
		}
	}

	if len(wrong) == 0 {
		return nil
	}

	slices.Sort(wrong)

	return fmt.Errorf("%w: %s. Write %s or %s", errLevel, strings.Join(wrong, ", "),
		config.LevelBasic, config.LevelAdvanced)
}

func checkDocumented(blocks []block) error {
	var missing []string

	for _, one := range blocks {
		for _, each := range one.Rows {
			if strings.TrimSpace(each.Doc) == "" {
				missing = append(missing, each.Path)
			}
		}
	}

	if len(missing) == 0 {
		return nil
	}

	slices.Sort(missing)

	return fmt.Errorf("%w: %s. Add a row to config.Keys or resource.Keys",
		errUndocumented, strings.Join(missing, ", "))
}

// checkUnknown fails on a row for a key no struct has, as a renamed or
// removed key leaves behind.
func checkUnknown(blocks []block) error {
	known := pathsOf(blocks)

	var stale []string

	for _, table := range []map[string]config.Key{config.Keys, resource.Keys} {
		for path := range table {
			if _, ok := known[path]; !ok {
				stale = append(stale, path)
			}
		}
	}

	if len(stale) == 0 {
		return nil
	}

	slices.Sort(stale)

	return fmt.Errorf("%w: %s. Remove the row, or restore the key",
		errUnknownKey, strings.Join(stale, ", "))
}

func checkLength(blocks []block) error {
	var long []string

	for _, one := range blocks {
		for _, each := range one.Rows {
			if words := len(strings.Fields(each.Doc)); words > maxWords {
				long = append(long, fmt.Sprintf("%s (%d words)", each.Path, words))
			}
		}
	}

	if len(long) == 0 {
		return nil
	}

	slices.Sort(long)

	return fmt.Errorf("%w: %s. %d words at most", errLongSentence, strings.Join(long, ", "), maxWords)
}

// region is the generated part of a page: one table per block.
func region(blocks []block) []byte {
	var body strings.Builder

	for index, one := range blocks {
		if index > 0 {
			body.WriteString("\n")
		}

		body.WriteString(render(one))
	}

	return pageRegion.Wrap(regionSubject, regionFix, body.String())
}

// renderPage returns the committed page with its region replaced.
func renderPage(path string, body []byte) ([]byte, error) {
	committed, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	spliced, err := pageRegion.Splice(committed, body)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}

	return spliced, nil
}

// checkSee refuses a See that names no page. A route is a page when a file of
// that name is in dir, or when a page there names it as its slug.
func checkSee(dir string, tables ...map[string]config.Key) error {
	var missing []string

	for _, table := range tables {
		for path, key := range table {
			if key.See != "" && !pageExists(dir, strings.TrimSuffix(key.See, "/")) {
				missing = append(missing, path+" ("+key.See+")")
			}
		}
	}

	if len(missing) == 0 {
		return nil
	}

	slices.Sort(missing)

	return fmt.Errorf("%w: %s. Name a page under %s", errSee, strings.Join(missing, ", "), dir)
}

func pageExists(dir, route string) bool {
	for _, extension := range []string{".md", ".mdx"} {
		if _, err := os.Stat(filepath.Join(dir, route+extension)); err == nil {
			return true
		}
	}

	pages, err := filepath.Glob(filepath.Join(dir, "*.md"))
	if err != nil {
		return false
	}

	for _, page := range pages {
		content, readErr := os.ReadFile(page)
		if readErr == nil && strings.Contains(string(content), "\nslug: "+route+"\n") {
			return true
		}
	}

	return false
}
