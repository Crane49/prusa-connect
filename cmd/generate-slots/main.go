// Command generate-slots writes every file that lists the module UI slots,
// from the slot table in sdk/manifest:
//
//	internal/transport/http/httpapi/contributes_gen.go  the wire struct
//	internal/app/resourcehost/contributes_gen.go        the manifest-to-wire mapping
//	packages/svelte/src/slots/generated.ts              the library's slot contract
//	docs/src/content/docs/reference/module-slots.md     the reference
//	docs/src/content/docs/writing-a-module.md           the region "Where each contribution lands"
//
// Run via: make generate-slots, gated by make slots-check.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/sdk/manifest"
)

const (
	defaultWirePath       = "internal/transport/http/httpapi/contributes_gen.go"
	defaultMappingPath    = "internal/app/resourcehost/contributes_gen.go"
	defaultTypeScriptPath = "packages/svelte/src/slots/generated.ts"
	defaultReferencePath  = "docs/src/content/docs/reference/module-slots.md"
	defaultGuidePath      = "docs/src/content/docs/writing-a-module.md"

	// generatedNotice heads every generated file.
	generatedNotice = "Code generated by make generate-slots from the slot table in sdk/manifest. DO NOT EDIT."
)

// errStale means a committed file differs from the generated one.
var errStale = errors.New("committed artefact differs from the slot table")

type options struct {
	wirePath       string
	mappingPath    string
	typescriptPath string
	referencePath  string
	guidePath      string
	check          bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.wirePath, "wire", defaultWirePath, "path of the generated wire struct")
	flag.StringVar(&opts.mappingPath, "mapping", defaultMappingPath, "path of the generated manifest-to-wire mapping")
	flag.StringVar(
		&opts.typescriptPath,
		"typescript",
		defaultTypeScriptPath,
		"path of the library's generated slot contract",
	)
	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath, "path of the published slot reference")
	flag.StringVar(&opts.guidePath, "guide", defaultGuidePath, "path of the guide holding the generated region")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed files against the generated ones and write nothing")
	flag.Parse()

	if err := run(manifest.Slots(), opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-slots: %v\n", err)
		os.Exit(1)
	}
}

func run(slots []manifest.Slot, opts options) error {
	wire, err := renderWire(slots)
	if err != nil {
		return err
	}

	mapping, err := renderMapping(slots)
	if err != nil {
		return err
	}

	guide, err := spliceGuide(opts.guidePath, slots)
	if err != nil {
		return err
	}

	outputs := []struct {
		path string
		body []byte
	}{
		{opts.wirePath, wire},
		{opts.mappingPath, mapping},
		{opts.typescriptPath, renderTypeScript(slots, manifest.Icons())},
		{opts.referencePath, renderReference(slots)},
		{opts.guidePath, guide},
	}

	if opts.check {
		var failures []error
		for _, out := range outputs {
			failures = append(failures, codegen.CompareFile(out.path, out.body, errStale, "generate-slots"))
		}

		return errors.Join(failures...)
	}

	for _, out := range outputs {
		if err = codegen.WriteFile(out.path, out.body); err != nil {
			return err
		}
	}

	fmt.Fprintf(os.Stderr, "OK slot contract: %d slots\n", len(slots))

	return nil
}
