// Command generate-printer-error-codes writes the title and the text of every
// Buddy and MMU printer error code to packages/svelte/locales/en.printerCode.json.
// The words are downloaded from one commit of Prusa-Error-Codes on GitHub. The
// file records that commit, and a run without -commit reads it from there.
//
// A code is a printer number, a category and an error: 13807 is the MK4,
// category 8, error 07. An entry written XX807 covers every printer its
// printers list names, or every Buddy printer when it names none. The list is
// resolved the same way as in the prusa-errors Python package. A text with an
// unfilled placeholder such as "Dock %d" is left out.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/prusa3d/prusa-connect/internal/codegen"
)

const (
	defaultOutputPath = "packages/svelte/locales/en.printerCode.json"

	generatedNotice = "Generated by 'make generate-printer-error-codes' from " +
		"https://github.com/prusa3d/Prusa-Error-Codes at _commit. Do not edit."

	// sourceURL is one source file at one commit.
	sourceURL = "https://raw.githubusercontent.com/prusa3d/Prusa-Error-Codes/%s/yaml/%s"

	downloadTimeout = 30 * time.Second
	// sourceMaxBytes is the size limit of one source file.
	sourceMaxBytes = 4 << 20
)

// sourceFiles are the Buddy catalogue and the MMU one. A Buddy printer with
// an MMU reports MMU codes under number 04.
var sourceFiles = []string{"buddy-error-codes.yaml", "mmu-error-codes.yaml"}

// printerNumbers maps a catalogue printer name to its USB product id, the
// first two digits of a code. It mirrors Printer in prusaerrors/shared/codes.py.
//
//nolint:mnd // the USB product ids are the table; naming each would hide it.
var printerNumbers = map[string]int{
	"MMU": 4, "MINI": 12, "MK4": 13, "IX": 16, "XL": 17, "MK39": 21, "MK35": 23,
	"MK4S": 26, "MK39S": 27, "MK35S": 28, "M1": 29, "COREONE": 31, "COREONEL": 35,
	"COREONE_INDX": 36, "COREONEL_INDX": 37, "COREONE_OAK": 38, "XLP": 41,
}

// buddyPrinters is what an XX code with no printers list covers. It mirrors
// BUDDY in prusaerrors/connect/codes.py.
var buddyPrinters = []string{
	"MINI", "MK4", "IX", "XL", "MK35", "MK4S", "MK39", "MK39S", "MK35S",
	"COREONE", "COREONEL", "XLP", "COREONE_OAK", "COREONE_INDX", "COREONEL_INDX",
}

// alsoMeant lists the printers that run the same firmware as the key. A list
// that names the key covers them too.
var alsoMeant = map[string][]string{
	"MK4":     {"MK4S", "MK39", "MK39S"},
	"MK35":    {"MK35S"},
	"XL":      {"XLP"},
	"COREONE": {"COREONE_OAK"},
}

var codePattern = regexp.MustCompile(`^([0-9]{2}|XX)([0-9]{3})$`)

// commitPattern is a full commit hash. A branch name is refused because the
// commit it points at changes.
var commitPattern = regexp.MustCompile(`^[0-9a-f]{40}$`)

// unfilledPattern matches a placeholder the firmware fills in: %d, %s, %.3f,
// %04x. A percent sign after a number, as in "50% done", does not match.
var unfilledPattern = regexp.MustCompile(`%[-0-9.]*[a-zA-Z]`)

// sourceEntry is the part of a source file entry this command reads.
type sourceEntry struct {
	Code     string   `yaml:"code"`
	Printers []string `yaml:"printers"`
	Title    string   `yaml:"title"`
	Text     string   `yaml:"text"`
}

// Entry is one code: its last three digits, the printers that raise it and
// its words.
type Entry struct {
	Code     string
	Printers []int
	Title    string
	Text     string
}

// File is the part of the generated file a run without -commit reads: the
// Prusa-Error-Codes commit.
type File struct {
	Commit string `json:"_commit"`
}

// The keys of the generated file. The prefix names the driver because the
// codes belong to the Buddy firmware.
const (
	noticeKey = "_notice"
	commitKey = "_commit"
	keyPrefix = "printerCode.xbuddy."
	// wildcard is how the catalogue writes "every printer" in a code.
	wildcard = "XX"
	// printersMark comes before the printers a wording is for, in its key.
	printersMark = ".p"
)

func main() {
	commit := flag.String(
		"commit", "", "Prusa-Error-Codes commit to read; the one the generated file records when empty",
	)
	output := flag.String("output", defaultOutputPath, "path of the generated file")
	flag.Parse()

	if err := run(context.Background(), *commit, *output); err != nil {
		fmt.Fprintf(os.Stderr, "generate-printer-error-codes: %v\n", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, commit, output string) error {
	if commit == "" {
		committed, err := codegen.ReadCatalogue[File](output)
		if err != nil {
			return err
		}

		if committed == nil {
			return fmt.Errorf("%s does not exist, so name the commit to read with -commit", output)
		}

		commit = committed.Commit
	}

	if !commitPattern.MatchString(commit) {
		return fmt.Errorf("commit %q is not a full 40 character commit hash", commit)
	}

	var entries []sourceEntry

	for _, name := range sourceFiles {
		data, err := download(ctx, fmt.Sprintf(sourceURL, commit, name))
		if err != nil {
			return err
		}

		read, err := parseSource(name, data)
		if err != nil {
			return err
		}

		entries = append(entries, read...)
	}

	rendered, err := render(commit, entries)
	if err != nil {
		return err
	}

	return codegen.WriteFile(output, rendered)
}

func download(ctx context.Context, address string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, downloadTimeout)
	defer cancel()

	request, err := http.NewRequestWithContext(ctx, http.MethodGet, address, nil)
	if err != nil {
		return nil, fmt.Errorf("build request for %s: %w", address, err)
	}

	response, err := http.DefaultClient.Do(request)
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", address, err)
	}
	defer func() { _ = response.Body.Close() }()

	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: GitHub answered %s", address, response.Status)
	}

	data, err := io.ReadAll(io.LimitReader(response.Body, sourceMaxBytes+1))
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", address, err)
	}

	if len(data) > sourceMaxBytes {
		return nil, fmt.Errorf("download %s: larger than %d bytes", address, sourceMaxBytes)
	}

	return data, nil
}

func parseSource(name string, data []byte) ([]sourceEntry, error) {
	var file struct {
		Errors []sourceEntry `yaml:"Errors"`
	}

	if err := yaml.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("decode %s: %w", name, err)
	}

	if len(file.Errors) == 0 {
		return nil, fmt.Errorf("%s holds no error code", name)
	}

	return file.Errors, nil
}

func render(commit string, entries []sourceEntry) ([]byte, error) {
	lines := map[string]string{noticeKey: generatedNotice, commitKey: commit}
	seen := map[string]string{}

	// widest is the XX entry of each code that covers the most printers. It
	// keeps XX in its key. The others get their printers in the key.
	resolved := make([]Entry, 0, len(entries))
	widest := map[string]int{}

	for index, entry := range entries {
		one, err := resolve(entry)
		if err != nil {
			return nil, err
		}

		// Two entries for one printer and one code would make the words
		// depend on file order. prusa-errors refuses it too.
		for _, printer := range one.Printers {
			key := fmt.Sprintf("%02d%s", printer, one.Code)
			if first, taken := seen[key]; taken {
				return nil, fmt.Errorf("code %s is defined twice, as %q and %q", key, first, entry.Title)
			}

			seen[key] = entry.Title
		}

		resolved = append(resolved, one)

		if !strings.HasPrefix(entry.Code, wildcard) {
			continue
		}

		if best, found := widest[one.Code]; !found || len(one.Printers) > len(resolved[best].Printers) {
			widest[one.Code] = index
		}
	}

	for index, one := range resolved {
		best, found := widest[one.Code]
		code := fmt.Sprintf("%02d%s", one.Printers[0], one.Code)

		switch {
		case found && best == index:
			code = wildcard + one.Code
		case strings.HasPrefix(entries[index].Code, wildcard):
			code = wildcard + one.Code + printersMark + printerList(one.Printers)
		}

		lines[keyPrefix+code+".title"] = one.Title

		if !unfilledPattern.MatchString(one.Text) {
			lines[keyPrefix+code+".text"] = one.Text
		}
	}

	var out bytes.Buffer

	// encoding/json sorts map keys, so the output order is stable.
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")

	if err := encoder.Encode(lines); err != nil {
		return nil, fmt.Errorf("encode: %w", err)
	}

	return out.Bytes(), nil
}

// printerList formats printers for a key: 17_41.
func printerList(printers []int) string {
	numbers := make([]string, 0, len(printers))
	for _, printer := range printers {
		numbers = append(numbers, fmt.Sprintf("%02d", printer))
	}

	return strings.Join(numbers, "_")
}

// resolve works out the printers one source entry covers.
func resolve(entry sourceEntry) (Entry, error) {
	parts := codePattern.FindStringSubmatch(entry.Code)
	if parts == nil {
		return Entry{}, fmt.Errorf("code %q is not two digits or XX and three digits", entry.Code)
	}

	names := []string{}

	switch {
	case parts[1] != wildcard:
		number := 0
		_, _ = fmt.Sscanf(parts[1], "%d", &number)

		return Entry{Code: parts[2], Printers: []int{number}, Title: entry.Title, Text: entry.Text}, nil
	case len(entry.Printers) == 0:
		names = append(names, buddyPrinters...)
	default:
		for _, listed := range entry.Printers {
			name := strings.ReplaceAll(strings.ToUpper(listed), ".", "")
			names = append(names, name)
			names = append(names, alsoMeant[name]...)
		}
	}

	printers := make([]int, 0, len(names))

	for _, name := range names {
		number, known := printerNumbers[name]
		if !known {
			return Entry{}, fmt.Errorf("code %s names printer %q, which has no number here", entry.Code, name)
		}

		if !slices.Contains(printers, number) {
			printers = append(printers, number)
		}
	}

	slices.Sort(printers)

	return Entry{Code: parts[2], Printers: printers, Title: entry.Title, Text: entry.Text}, nil
}
