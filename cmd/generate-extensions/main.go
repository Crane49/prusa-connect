// Command generate-extensions writes the plugin-author reference from the
// extension registries: docs/extensions/extensions.json for machines and
// docs/src/content/docs/extensions.md for people.
//
// An entry in the committed catalogue that is not registered stops the run,
// because an operator's configuration may still name it. -allow-removals
// retires an entry on purpose, in a breaking release only. With -check it
// writes nothing and fails when a committed file differs.
//
// Run via: make generate-extensions, gated by make extensions-check.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/sdk/extension"

	// The catalogue is filled at package init. internal/app/builtin
	// blank-imports every adapters/ package, so this command reads the same set
	// the binary ships. The driver under internal/connector needs its own line.
	_ "github.com/prusa3d/prusa-connect/internal/app/builtin"
	_ "github.com/prusa3d/prusa-connect/internal/connector/xbuddy"
)

const (
	defaultCataloguePath = "docs/extensions/extensions.json"
	defaultReferencePath = "docs/src/content/docs/extensions.md"

	// generatedNotice is the first thing in both artefacts.
	generatedNotice = "Generated by 'make generate-extensions' from the extension registries. " +
		"Do not edit: change the registration in Go and regenerate."
)

var (
	// errEntriesRemoved means a committed entry is not registered.
	errEntriesRemoved = errors.New("extension entries vanished from the registries")
	// errStale means a committed file differs from the generated one.
	errStale = errors.New("committed artefact differs from the registries")
)

// catalogueFile is the JSON file: the Snapshot() bytes and a $comment that
// says where the file came from.
type catalogueFile struct {
	Comment string          `json:"$comment"`
	Entries json.RawMessage `json:"extensions"`
}

type options struct {
	cataloguePath string
	referencePath string
	check         bool
	allowRemovals bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.cataloguePath, "catalogue", defaultCataloguePath,
		"path of the machine-readable catalogue file")
	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath,
		"path of the human-readable plugin reference")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed artefacts against the generated ones and write nothing")
	flag.BoolVar(&opts.allowRemovals, "allow-removals", false,
		"let an entry disappear. An operator's configuration still names it: for a deliberate "+
			"retirement in a breaking release only")
	flag.Parse()

	if err := run(extension.Global(), opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-extensions: %v\n", err)
		os.Exit(1)
	}
}

func run(catalogue *extension.Catalogue, opts options) error {
	entries := catalogue.All()

	committed, err := readCatalogueFile(opts.cataloguePath)
	if err != nil {
		return err
	}

	if err = errors.Join(
		checkDuplicates("the registries", entries),
		checkDuplicates(opts.cataloguePath, committed),
	); err != nil {
		return err
	}

	if err = checkRemovals(diffCatalogue(committed, entries), opts.allowRemovals); err != nil {
		return err
	}

	snapshot, err := catalogue.Snapshot()
	if err != nil {
		return err
	}

	machine, err := renderCatalogueFile(snapshot)
	if err != nil {
		return err
	}

	human := renderReference(entries)

	if opts.check {
		return errors.Join(
			compareFile(opts.cataloguePath, machine),
			compareFile(opts.referencePath, human),
		)
	}

	if err = codegen.WriteFile(opts.cataloguePath, machine); err != nil {
		return err
	}

	if err = codegen.WriteFile(opts.referencePath, human); err != nil {
		return err
	}

	fmt.Fprintf(os.Stderr, "OK extension catalogue: %s (%d entries)\n", opts.cataloguePath, len(entries))
	fmt.Fprintf(os.Stderr, "OK extension reference: %s\n", opts.referencePath)

	return nil
}

func checkRemovals(diff catalogueDiff, allowRemovals bool) error {
	if len(diff.Removed) == 0 || allowRemovals {
		return nil
	}

	return fmt.Errorf(
		"%w: %s\n  an operator's configuration still names %s. Restore the registration, or pass "+
			"-allow-removals if this is a deliberate retirement in a breaking release",
		errEntriesRemoved,
		strings.Join(entryNames(diff.Removed), ", "),
		pluralise(len(diff.Removed), "it", "them"),
	)
}

// readCatalogueFile reads the committed catalogue. A missing file is the first
// run and returns no entries.
func readCatalogueFile(path string) ([]extension.Descriptor, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}

	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	var file catalogueFile
	if err = json.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("decode %s: %w", path, err)
	}

	var entries []extension.Descriptor
	if err = json.Unmarshal(file.Entries, &entries); err != nil {
		return nil, fmt.Errorf("decode entries in %s: %w", path, err)
	}

	return entries, nil
}

func renderCatalogueFile(snapshot []byte) ([]byte, error) {
	encoded, err := json.MarshalIndent(catalogueFile{
		Comment: generatedNotice,
		Entries: snapshot,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode catalogue file: %w", err)
	}

	return append(encoded, '\n'), nil
}

func compareFile(path string, want []byte) error {
	return codegen.CompareFile(path, want, errStale, "generate-extensions")
}

func pluralise(n int, one, many string) string {
	if n == 1 {
		return one
	}

	return many
}
