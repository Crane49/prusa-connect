// Command generate-error-codes writes the error taxonomy from the fault
// registry: docs/errors/error-codes.json for machines and
// docs/src/content/docs/error-codes.md for people.
//
// A code in the committed registry file that is missing from the registry
// stops the run, because clients still handle it. -allow-removals retires a
// code on purpose, in a breaking release only. With -check it writes nothing
// and fails when a committed file differs.
//
// Run via: make generate-error-codes, gated by make error-codes-check.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/sdk/fault"

	// The registry is filled at package init. Every package that registers
	// codes needs a blank import here.
	_ "github.com/prusa3d/prusa-connect/internal/app/resourcehost"
	_ "github.com/prusa3d/prusa-connect/internal/authz"
	_ "github.com/prusa3d/prusa-connect/internal/connector/xbuddy"
	_ "github.com/prusa3d/prusa-connect/internal/extension/supervisor"
	_ "github.com/prusa3d/prusa-connect/internal/transport/http/httpfault"
	_ "github.com/prusa3d/prusa-connect/sdk/connectorapi"
)

const (
	defaultRegistryPath  = "docs/errors/error-codes.json"
	defaultReferencePath = "docs/src/content/docs/error-codes.md"

	// generatedNotice is the first thing in both artefacts.
	generatedNotice = "Generated by 'make generate-error-codes' from the fault registry. " +
		"Do not edit: change the registration in Go and regenerate."
)

var (
	// errCodesRemoved means a committed code is missing from the registry.
	errCodesRemoved = errors.New("codes vanished from the registry")
	// errStale means a committed file differs from the generated one.
	errStale = errors.New("committed artefact differs from the generated one")
)

// registryFile is the JSON file: the Snapshot() bytes, the param key set and
// a $comment that says where the file came from.
type registryFile struct {
	Comment   string          `json:"$comment"`
	ParamKeys []string        `json:"param_keys"`
	Codes     json.RawMessage `json:"codes"`
}

type options struct {
	registryPath  string
	referencePath string
	check         bool
	allowRemovals bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.registryPath, "registry", defaultRegistryPath, "path of the machine-readable registry file")
	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath, "path of the human-readable error reference")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed artefacts against the generated ones and write nothing")
	flag.BoolVar(&opts.allowRemovals, "allow-removals", false,
		"let a code disappear. Clients are still handling it: for a deliberate retirement in a breaking release only")
	flag.Parse()

	if err := run(fault.Global(), opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-error-codes: %v\n", err)
		os.Exit(1)
	}
}

func run(registry *fault.Registry, opts options) error {
	entries := registry.All()

	committed, err := readRegistryFile(opts.registryPath)
	if err != nil {
		return err
	}

	if err = checkRemovals(diffRegistry(committed, entries), opts.allowRemovals); err != nil {
		return err
	}

	if err = checkParamKeys(entries); err != nil {
		return err
	}

	snapshot, err := registry.Snapshot()
	if err != nil {
		return err
	}

	machine, err := renderRegistryFile(snapshot)
	if err != nil {
		return err
	}

	human, err := renderReference(entries)
	if err != nil {
		return err
	}

	if opts.check {
		return errors.Join(
			compareFile(opts.registryPath, machine),
			compareFile(opts.referencePath, human),
		)
	}

	if err = codegen.WriteFile(opts.registryPath, machine); err != nil {
		return err
	}

	if err = codegen.WriteFile(opts.referencePath, human); err != nil {
		return err
	}

	fmt.Fprintf(os.Stderr, "✓ error registry:  %s (%d codes)\n", opts.registryPath, len(entries))
	fmt.Fprintf(os.Stderr, "✓ error reference: %s\n", opts.referencePath)

	return nil
}

func checkRemovals(diff registryDiff, allowRemovals bool) error {
	if len(diff.Removed) == 0 || allowRemovals {
		return nil
	}

	return fmt.Errorf(
		"%w: %s\n  a released client still branches on %s. Restore the registration, or pass -allow-removals "+
			"if this is a deliberate retirement in a breaking release",
		errCodesRemoved,
		strings.Join(codeStrings(diff.Removed), ", "),
		pluralise(len(diff.Removed), "it", "them"),
	)
}

// readRegistryFile reads the committed registry. A missing file is the first
// run and returns no entries.
func readRegistryFile(path string) ([]fault.Entry, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}

	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	var file registryFile
	if err = json.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("decode %s: %w", path, err)
	}

	var entries []fault.Entry
	if err = json.Unmarshal(file.Codes, &entries); err != nil {
		return nil, fmt.Errorf("decode codes in %s: %w", path, err)
	}

	return entries, nil
}

func renderRegistryFile(snapshot []byte) ([]byte, error) {
	encoded, err := json.MarshalIndent(registryFile{
		Comment:   generatedNotice,
		ParamKeys: fault.ParamKeys(),
		Codes:     snapshot,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode registry file: %w", err)
	}

	return append(encoded, '\n'), nil
}

func compareFile(path string, want []byte) error {
	return codegen.CompareFile(path, want, errStale, "generate-error-codes")
}

func pluralise(n int, one, many string) string {
	if n == 1 {
		return one
	}

	return many
}
