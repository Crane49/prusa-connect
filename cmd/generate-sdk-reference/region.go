package main

import (
	"fmt"
	"strings"

	"github.com/prusa3d/prusa-connect/internal/codegen"
)

// The region protocol is codegen.Region: a page has one generated region
// between two marker comments. Everything outside them is written by hand.

const (
	// regionStartPrefix opens the region. The subject follows it.
	regionStartPrefix = "<!-- generated by make " + makeTarget + " for "

	// regionEnd closes the region, on a line of its own.
	regionEnd = "<!-- end generated -->"

	// placeholderMark is in the intro of a page this command created, until
	// a person writes the intro. A page with it must not ship.
	placeholderMark = "TODO"
)

// errNoRegion means a page exists but has no marker pair.
var errNoRegion = codegen.ErrNoRegion

// pageRegion is the marker pair of every page this command writes.
var pageRegion = codegen.Region{Start: regionStartPrefix, End: regionEnd}

// regionOf wraps a body in the two markers. subject is named in the opening
// marker. fix tells a person what to change instead of the region.
func regionOf(subject, fix, body string) []byte {
	return pageRegion.Wrap(subject, fix, body)
}

func splice(committed, region []byte) ([]byte, error) {
	return pageRegion.Splice(committed, region)
}

// handWritten returns everything outside the markers.
func handWritten(committed []byte) (string, error) {
	return pageRegion.HandWritten(committed)
}

// frontMatter is what docs/src/content.config.ts requires of a page. It is
// written once, when the page is created.
type frontMatter struct {
	title       string
	description string
	// audience is run for an API or extension page and extend for a Go page.
	audience string
	// order is the page's place in its sidebar group, or 0 for none.
	order         int
	implementedBy []string
}

func (f frontMatter) String() string {
	var out strings.Builder

	out.WriteString("---\n")
	fmt.Fprintf(&out, "title: %s\n", yamlString(f.title))
	fmt.Fprintf(&out, "description: %s\n", yamlString(f.description))
	fmt.Fprintf(&out, "audience: %s\n", f.audience)

	if f.order > 0 {
		fmt.Fprintf(&out, "sidebar:\n  order: %d\n", f.order)
	}

	out.WriteString("rewrite:\n  describes: current\n  implementedBy:\n")

	for _, path := range f.implementedBy {
		fmt.Fprintf(&out, "    - %s\n", path)
	}

	out.WriteString("---\n")

	return out.String()
}

// yamlString returns a double-quoted YAML scalar, so a colon or a quote in
// the text cannot break the front matter.
func yamlString(text string) string {
	escaped := strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(text)

	return `"` + escaped + `"`
}

// freshPage is the whole file for a page that is not committed: the front
// matter, the placeholder intro and the region.
func freshPage(front frontMatter, placeholder string, region []byte) []byte {
	var out strings.Builder

	out.WriteString(front.String())
	out.WriteString("\n")
	out.WriteString(placeholder)
	out.WriteString("\n\n")
	out.Write(region)
	out.WriteString("\n")

	return []byte(out.String())
}
