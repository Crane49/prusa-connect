// Command generate-wire-protocol writes docs/wire/plugin-wire-protocol.json
// from sdk/wire and sdk/wire/wiretest: the sizes, the frame kinds and every
// test vector of the plugin wire protocol. An implementation in another
// language tests itself against this file. The prose specification is
// docs/src/content/docs/plugin-wire-protocol.md.
//
// With -check it writes nothing and fails when the committed file differs.
//
// Run via: make generate-wire-protocol, gated by make wire-check.
package main

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/prusa3d/prusa-connect/sdk/wire"
	"github.com/prusa3d/prusa-connect/sdk/wire/wiretest"
)

const (
	defaultArtefactPath = "docs/wire/plugin-wire-protocol.json"

	// The permissions every generator in cmd/ writes with.
	dirPerms  = 0o750
	filePerms = 0o600

	// artefactFormat is the version of the file's shape. Raise it when a
	// member is removed or changes meaning.
	artefactFormat = "1.0"

	// artefactVersion is the version of the content. Raise it when a vector,
	// a kind or a size changes.
	artefactVersion = "1.0.0"

	// generatedNotice is the first member of the artefact.
	generatedNotice = "Generated by 'make generate-wire-protocol' from sdk/wire and sdk/wire/wiretest. " +
		"Do not edit: change the Go and regenerate."
)

func main() {
	path := flag.String("artefact", defaultArtefactPath,
		"path of the machine-readable wire protocol artefact")
	check := flag.Bool("check", false,
		"compare the committed artefact against the generated one and write nothing")
	flag.Parse()

	if err := run(*path, *check); err != nil {
		fmt.Fprintf(os.Stderr, "generate-wire-protocol: %v\n", err)
		os.Exit(1)
	}
}

func run(path string, check bool) error {
	generated, err := artefact()
	if err != nil {
		return err
	}

	encoded, err := json.MarshalIndent(generated, "", "  ")
	if err != nil {
		return fmt.Errorf("encode the artefact: %w", err)
	}

	encoded = append(encoded, '\n')

	if check {
		return compare(path, encoded)
	}

	return write(path, encoded)
}

// compare checks the committed file against the generated one. CRLF from a
// Windows checkout is normalised first.
func compare(path string, encoded []byte) error {
	committed, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read the committed artefact: %w", err)
	}

	if !bytes.Equal(bytes.ReplaceAll(committed, []byte("\r\n"), []byte("\n")), encoded) {
		return fmt.Errorf("%s is not what sdk/wire and sdk/wire/wiretest generate. "+
			"Run make generate-wire-protocol and commit the result", path)
	}

	fmt.Fprintf(os.Stderr, "OK %s matches sdk/wire and sdk/wire/wiretest\n", path)

	return nil
}

func write(path string, encoded []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), dirPerms); err != nil {
		return fmt.Errorf("create the artefact directory: %w", err)
	}

	if err := os.WriteFile(path, encoded, filePerms); err != nil {
		return fmt.Errorf("write the artefact: %w", err)
	}

	fmt.Fprintf(os.Stderr, "wrote %s\n", path)

	return nil
}

// artefact builds the whole file. It fails when a vector section is empty.
func artefact() (Document, error) {
	doc := Document{
		Generated: generatedNotice,
		Format:    artefactFormat,
		Version:   artefactVersion,
		Protocol: Protocol{
			Major:    wire.ProtocolMajor,
			MinMinor: wire.MinMinor,
			MaxMinor: wire.MaxMinor,
		},
		Sizes: Sizes{
			HeaderBytes:            wire.HeaderBytes,
			ByteOrder:              "big-endian",
			DefaultMaxPayloadBytes: wire.DefaultMaxPayloadBytes,
			ChunkBytes:             wire.ChunkBytes,
			MaxResetBytes:          wire.MaxResetBytes,
			CreditBytes:            wire.CreditBytes,
			MaxCredit:              wire.MaxCredit,
			MaxHandshakeBytes:      wire.MaxHandshakeBytes,
		},
	}

	for _, kind := range wire.Kinds() {
		doc.Kinds = append(doc.Kinds, Kind{
			Code:    uint8(kind.Kind),
			Name:    kind.Name,
			Summary: kind.Summary,
			Payload: kind.Payload,
		})
	}

	for _, reason := range wiretest.Reasons() {
		doc.Reasons = append(doc.Reasons, string(reason))
	}

	for _, vector := range wiretest.Frames() {
		payload, err := vector.Payload()
		if err != nil {
			return Document{}, err
		}

		frame := Frame{
			Name:      vector.Name,
			Doc:       vector.Doc,
			Stream:    uint32(vector.Stream),
			Kind:      vector.Kind.String(),
			HeaderHex: vector.HeaderHex,
		}

		if vector.Repeat.Count > 0 {
			frame.PayloadRepeat = &Repeat{Byte: vector.Repeat.Byte, Count: vector.Repeat.Count}
		} else {
			frame.PayloadHex = hex.EncodeToString(payload)
		}

		doc.Frames = append(doc.Frames, frame)
	}

	for _, vector := range wiretest.Refusals() {
		refusal := Refusal{
			Name:            vector.Name,
			Doc:             vector.Doc,
			BytesHex:        vector.BytesHex,
			MaxPayloadBytes: vector.MaxPayloadBytes,
			Reason:          string(vector.Reason),
		}

		if vector.Repeat.Count > 0 {
			refusal.BytesRepeat = &Repeat{Byte: vector.Repeat.Byte, Count: vector.Repeat.Count}
		}

		doc.Refusals = append(doc.Refusals, refusal)
	}

	for _, vector := range wiretest.Handshakes() {
		entry := HandshakeCase{
			Name:     vector.Name,
			Doc:      vector.Doc,
			Line:     vector.Line,
			Accepted: vector.Accepted,
			Reason:   string(vector.Reason),
		}

		if vector.Accepted {
			entry.Read = &Handshake{
				Protocol: vector.Handshake.Protocol,
				MinMinor: vector.Handshake.MinMinor,
				MaxMinor: vector.Handshake.MaxMinor,
				Address:  vector.Handshake.Address,
			}
		}

		doc.Handshakes = append(doc.Handshakes, entry)
	}

	for _, vector := range wiretest.Negotiations() {
		doc.Negotiations = append(doc.Negotiations, Negotiation{
			Name: vector.Name,
			Doc:  vector.Doc,
			Host: Handshake{
				Protocol: vector.Host.Protocol,
				MinMinor: vector.Host.MinMinor,
				MaxMinor: vector.Host.MaxMinor,
				Address:  vector.Host.Address,
			},
			Child: Handshake{
				Protocol: vector.Child.Protocol,
				MinMinor: vector.Child.MinMinor,
				MaxMinor: vector.Child.MaxMinor,
				Address:  vector.Child.Address,
			},
			Accepted: vector.Accepted,
			Minor:    vector.Minor,
			Reason:   string(vector.Reason),
		})
	}

	if len(doc.Frames) == 0 || len(doc.Refusals) == 0 || len(doc.Handshakes) == 0 || len(doc.Negotiations) == 0 {
		return Document{}, fmt.Errorf(
			"the vector set is missing a whole section: %d frames, %d refusals, %d handshakes, %d negotiations",
			len(doc.Frames), len(doc.Refusals), len(doc.Handshakes), len(doc.Negotiations),
		)
	}

	return doc, nil
}
