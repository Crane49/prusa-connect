// Command generate-resource-kinds writes the resource-kind vocabulary from the
// descriptor table in internal/kernel/ref:
// docs/vocabularies/resource-kinds.json for machines and
// docs/src/content/docs/resource-kinds.md for people.
//
// A committed kind that nothing declares stops the run unless -allow-removals
// is set, because a client or a configuration may still name it. With -check
// it writes nothing and fails when a committed file differs.
//
// Run via: make generate-resource-kinds, gated by make resource-kinds-check.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/internal/kernel/ref"
)

const (
	defaultCataloguePath = "docs/vocabularies/resource-kinds.json"
	defaultReferencePath = "docs/src/content/docs/resource-kinds.md"

	// generatedNotice is the first thing in both artefacts.
	generatedNotice = "Generated by 'make generate-resource-kinds' from the descriptor table this " +
		"build links. Do not edit: change the table in Go and regenerate."
)

type options struct {
	cataloguePath string
	referencePath string
	check         bool
	allowRemovals bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.cataloguePath, "catalogue", defaultCataloguePath,
		"path of the machine-readable resource-kind set")
	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath,
		"path of the published resource-kind reference")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed artefacts against the generated ones and write nothing")
	flag.BoolVar(&opts.allowRemovals, "allow-removals", false,
		"let a kind disappear. An operator's configuration still names it: for a deliberate "+
			"retirement in a breaking release only")
	flag.Parse()

	if err := run(ref.KindDocs(), opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-resource-kinds: %v\n", err)
		os.Exit(1)
	}
}

func run(entries []ref.KindDoc, opts options) error {
	committed, err := codegen.ReadCatalogue[catalogueFile](opts.cataloguePath)
	if err != nil {
		return err
	}

	// A declared kind missing from the committed file fails only under -check.
	// A generate run is how it gets added.
	if err = errors.Join(
		checkDescribed(entries),
		checkRuntimesDescribed(entries, ref.RuntimeDocs()),
		checkRetired(committed, entries, opts.allowRemovals),
	); err != nil {
		return err
	}

	machine, err := renderCatalogue(entries)
	if err != nil {
		return err
	}

	human := renderReference(entries)

	if opts.check {
		return errors.Join(
			checkDrift(committed, entries, opts.allowRemovals),
			checkRuntimeDrift(committed, ref.RuntimeDocs(), opts.allowRemovals),
			compareFile(opts.cataloguePath, machine),
			compareFile(opts.referencePath, human),
		)
	}

	if err = codegen.WriteFile(opts.cataloguePath, machine); err != nil {
		return err
	}

	if err = codegen.WriteFile(opts.referencePath, human); err != nil {
		return err
	}

	fmt.Fprintf(os.Stderr, "OK resource-kind set: %s (%d kinds)\n", opts.cataloguePath, len(entries))
	fmt.Fprintf(os.Stderr, "OK resource-kind reference: %s\n", opts.referencePath)

	return nil
}
