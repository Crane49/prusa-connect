// Command generate-device-models publishes the device-model vocabulary from the
// catalogue in internal/printer/profile, and gates it.
//
// It writes two files. Nobody edits them by hand:
//
//	docs/vocabularies/device-models.json      the machine-readable set
//	docs/src/content/docs/device-models.md    the reference a client reads
//
// The command fails when the catalogue has a model that the committed JSON
// file does not have. It also fails when the committed file has a model that
// the catalogue does not have, because a client may still look up the model
// of a device record in the published file. With -check it writes nothing and
// fails when a committed file differs from the generated one.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"

	"github.com/prusa3d/prusa-connect/internal/codegen"
	"github.com/prusa3d/prusa-connect/internal/printer/profile"
)

const (
	defaultCataloguePath = "docs/vocabularies/device-models.json"
	defaultReferencePath = "docs/src/content/docs/device-models.md"

	// generatedNotice is the first thing in both artefacts.
	generatedNotice = "Generated by 'make generate-device-models' from the model catalogue this " +
		"build links. Do not edit: change the table in Go and regenerate."
)

// options is what the flags say.
type options struct {
	cataloguePath string
	referencePath string
	check         bool
	allowRemovals bool
}

func main() {
	opts := options{}

	flag.StringVar(&opts.cataloguePath, "catalogue", defaultCataloguePath,
		"path of the machine-readable device-model set")
	flag.StringVar(&opts.referencePath, "reference", defaultReferencePath,
		"path of the published device-model reference")
	flag.BoolVar(&opts.check, "check", false,
		"compare the committed artefacts against the generated ones and write nothing")
	flag.BoolVar(&opts.allowRemovals, "allow-removals", false,
		"let a model disappear. A client is still joining device records onto it: for a deliberate "+
			"retirement that was deprecated in an earlier release only")
	flag.Parse()

	if err := run(profile.ModelDocs(), opts); err != nil {
		fmt.Fprintf(os.Stderr, "generate-device-models: %v\n", err)
		os.Exit(1)
	}
}

func run(entries []profile.ModelDoc, opts options) error {
	committed, err := codegen.ReadCatalogue[catalogueFile](opts.cataloguePath)
	if err != nil {
		return err
	}

	if err = errors.Join(
		checkDescribed(entries),
		checkDrift(committed, entries, opts.allowRemovals, !opts.check),
	); err != nil {
		return err
	}

	machine, err := renderCatalogue(entries)
	if err != nil {
		return err
	}

	human := renderReference(entries)

	if opts.check {
		return errors.Join(
			compareFile(opts.cataloguePath, machine),
			compareFile(opts.referencePath, human),
		)
	}

	if err = codegen.WriteFile(opts.cataloguePath, machine); err != nil {
		return err
	}

	if err = codegen.WriteFile(opts.referencePath, human); err != nil {
		return err
	}

	fmt.Fprintf(os.Stderr, "OK device-model set: %s (%d models)\n", opts.cataloguePath, len(entries))
	fmt.Fprintf(os.Stderr, "OK device-model reference: %s\n", opts.referencePath)

	return nil
}
