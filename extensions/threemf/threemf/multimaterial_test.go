func TestPS3Multimaterial(t *testing.T) {
	t.Parallel()

	p := read(t, ps3MMProject(t))
	tower := p.Objects[0]

	if tower.Parts[0].Extruder != 2 || tower.Parts[1].Extruder != 3 {
		t.Errorf("parts %+v, want the object's extruder 2 and the part's 3", tower.Parts)
	}

	checkExtruders(t, "top", tower.Parts[1].PaintedExtruders, 1)
	checkExtruders(t, "Tower", tower.Extruders, 1, 2, 3)

	if len(tower.LayerRanges) != 1 || tower.LayerRanges[0].Extruder != 1 || tower.LayerRanges[0].MaxZ != 4 ||
		tower.LayerRanges[0].Settings["layer_height"] != "0.1" {
		t.Errorf("ranges %+v", tower.LayerRanges)
	}

	if tower.Painting != (threemf.Painting{Multimaterial: true, Seams: true}) {
		t.Errorf("painting %+v", tower.Painting)
	}

	setup := p.Setups[0]

	want := []threemf.Filament{
		{Extruder: 1, Color: "#FF0000", Type: "PLA"},
		{Extruder: 2, Color: "#222222", Type: "PETG"},
		{Extruder: 3, Color: "#0000FF", Type: "PLA"},
	}
	if !slices.Equal(setup.Filaments, want) {
		t.Errorf("filaments %+v", setup.Filaments)
	}

	if !setup.Beds[0].Sequential || !setup.Beds[1].Sequential {
		t.Errorf("beds are not printed object by object")
	}

	changes := []threemf.LayerChange{
		{Height: 1.2, Kind: threemf.LayerChangeColor, Extruder: 3, Color: "#00FF00"},
		{Height: 4.2, Kind: threemf.LayerChangeTool, Extruder: 1},
	}
	if !slices.Equal(setup.Beds[0].LayerChanges, changes) || len(setup.Beds[1].LayerChanges) != 0 {
		t.Errorf("changes %+v and %+v", setup.Beds[0].LayerChanges, setup.Beds[1].LayerChanges)
	}

	checkExtruders(t, "project", p.Extruders, 1, 2, 3)
}

// PrusaSlicer 2.9 encodes a state above 16 as 0b1100, 0b1110 and two more
// nibbles, low first. The text is read from its end: C, E, then 1 and 0, so
// 01EC is state 0x01 + 17 = 18.
func TestPS2LongPaintState(t *testing.T) {
	t.Parallel()

	settings := "; bed_shape = 0x0,250x0,250x210,0x210\n; max_print_height = 220\n; nozzle_diameter = " +
		strings.TrimSuffix(strings.Repeat("0.4,", 20), ",") + "\n"
	data := ps2ProjectWith(t, "PrusaSlicer-2.9.6", settings, nil, ps2Object{
		name:   "Long",
		places: []string{at(20, 20)},
		parts: []meshPart{
			{kind: "ModelPart", hi: [3]float64{10, 10, 10}, paint: `slic3rpe:mmu_segmentation="01EC"`},
		},
	})

	checkExtruders(t, "Long", read(t, data).Objects[0].Parts[0].PaintedExtruders, 18)
}
