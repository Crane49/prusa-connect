// The tests in this file pin how a project says which extruder prints what:
// the extruder of each part, the painting, the filaments, the layer changes
// and the print order. Each rule names the slicer source it follows in the
// code that implements it.

// paintedBox is box with attributes written into the first triangle, and
// rest into every other one.
func paintedBox(x, y, z float64, first, rest string) string {
	mesh := box(x, y, z)
	head, tail, _ := strings.Cut(mesh, "<triangles>")
	tris := strings.Split(strings.TrimSuffix(tail, "</triangles></mesh>"), "/>")

	var b strings.Builder

	b.WriteString(head + "<triangles>")

	for i, tri := range tris {
		if tri == "" {
			continue
		}

		attrs := rest
		if i == 0 {
			attrs = first
		}

		b.WriteString(tri + " " + attrs + "/>")
	}

	b.WriteString("</triangles></mesh>")

	return b.String()
}

