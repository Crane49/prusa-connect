// orcaMMObjects give Cube the third filament and Pin the second. Pin's part
// names the fifth, which OrcaSlicer drops from an object of one part.
const orcaMMObjects = `  <object id="2">
    <metadata key="name" value="Cube"/>
    <metadata key="extruder" value="3"/>
    <part id="1" subtype="normal_part"><metadata key="name" value="body"/><metadata key="sparse_infill_filament_id" value="6"/></part>
    <part id="5" subtype="negative_part"><metadata key="name" value="hole"/><metadata key="extruder" value="4"/></part>
  </object>
  <object id="4">
    <metadata key="name" value="Pin"/>
    <metadata key="extruder" value="2"/>
    <part id="3" subtype="normal_part"><metadata key="name" value="pin"/><metadata key="extruder" value="5"/></part>
  </object>
`

func TestOrcaMultimaterial(t *testing.T) {
	t.Parallel()

	colors := make([]string, 20)
	profiles := make([]string, 20)

	for i := range colors {
		colors[i] = fmt.Sprintf(`"#0000%02XFF"`, i)
		profiles[i] = `"Generic PLA"`
	}

	settings := `{"printable_area": ["0x0", "200x0", "200x200", "0x200"], "printable_height": "250",
"print_sequence": "by layer", "enable_support": "1", "support_type": "normal(auto)",
"support_filament": "4", "support_interface_filament": "0", "filament_colour": [` + strings.Join(colors, ",") + `],
"filament_settings_id": [` + strings.Join(profiles, ",") + `], "filament_type": ["PLA", "PETG"],
"gcode_label_objects": "1", "wipe_on_loops": "0"}`

	plates := `  <plate>
    <metadata key="plater_id" value="1"/>
    <metadata key="print_sequence" value="by object"/>
    <metadata key="gcode_file" value="Metadata/plate_1.gcode"/>
  </plate>
  <plate>
    <metadata key="plater_id" value="2"/>
    <metadata key="gcode_file" value="Metadata/plate_2.gcode"/>
  </plate>
`
	changes := `<?xml version="1.0" encoding="UTF-8"?>
<custom_gcodes_per_layer>
<plate>
<plate_info id="2"/>
<layer top_z="5" type="0" extruder="1" color="#FF00FF" extra="" gcode="M600"/>
<layer top_z="1" type="5" extruder="1" color="" extra="" gcode=""/>
<mode value="MultiAsSingle"/>
</plate>
</custom_gcodes_per_layer>
`
	// OrcaSlicer reads a state above 17 as 0b1111 and one more nibble:
	// 2FC is state 20, which PrusaSlicer would read as 18. EC is state 17.
	body := paintedBox(10, 10, 10, `paint_color="2FC"`, `paint_color="EC" paint_seam="4"`)
	data := orcaProjectFull(t, settings, orcaMMObjects, orcaParts(body), plates,
		entry{"Metadata/plate_2.gcode", "G28\n"},
		entry{"Metadata/custom_gcode_per_layer.xml", changes},
		entry{"Metadata/layer_config_ranges.xml", `<?xml version="1.0" encoding="utf-8"?>
<objects>
 <object id="2">
  <range min_z="1" max_z="3">
   <option opt_key="extruder">7</option>
  </range>
 </object>
</objects>
`},
	)

	p := read(t, data)
	cube, pin := p.Objects[0], p.Objects[1]

	if len(pin.LayerRanges) != 1 || pin.LayerRanges[0].Extruder != 7 || len(cube.LayerRanges) != 0 {
		t.Errorf("ranges %+v and %+v, want one on the second object", cube.LayerRanges, pin.LayerRanges)
	}

	if cube.Parts[0].Extruder != 3 || cube.Parts[1].Extruder != 0 || pin.Parts[0].Extruder != 2 {
		t.Errorf("parts %+v %+v", cube.Parts, pin.Parts)
	}

	checkExtruders(t, "body", cube.Parts[0].PaintedExtruders, 17, 20)
	checkExtruders(t, "Cube", cube.Extruders, 4, 17, 20)
	checkExtruders(t, "Pin", pin.Extruders, 2, 4, 7)
	checkExtruders(t, "project", p.Extruders, 2, 4, 7, 17, 20)

	if !cube.Painting.Multimaterial || !cube.Painting.Seams || cube.Painting.Supports {
		t.Errorf("Cube painting %+v", cube.Painting)
	}

	filaments := p.Setups[0].Filaments
	if len(filaments) != 20 || filaments[1] != (threemf.Filament{Extruder: 2, Color: "#000001", Type: "PETG"}) ||
		filaments[19].Color != "#000013" {
		t.Errorf("filaments %+v", filaments)
	}

	beds := p.Setups[0].Beds
	if len(beds) != 2 || !beds[0].Sequential || beds[1].Sequential {
		t.Fatalf("beds %+v, want plate 1 by object and plate 2 by layer", beds)
	}

	if beds[0].GCode != "" || beds[1].GCode != "Metadata/plate_2.gcode" {
		t.Errorf("G-code %q %q, want only the entry the archive holds", beds[0].GCode, beds[1].GCode)
	}

	want := []threemf.LayerChange{{Height: 5, Kind: threemf.LayerChangeColor, Extruder: 1, Color: "#FF00FF"}}
	if len(beds[0].LayerChanges) != 0 || !slices.Equal(beds[1].LayerChanges, want) {
		t.Errorf("changes %+v and %+v", beds[0].LayerChanges, beds[1].LayerChanges)
	}

	for _, issue := range p.Issues {
		if issue.Code == threemf.IssueGCodeOnly {
			t.Errorf("a project with objects is G-code only")
		}
	}
}

