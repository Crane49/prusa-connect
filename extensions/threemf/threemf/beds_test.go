// The tests in this file pin the bed rules the command lines cannot show,
// because a command line slices one bed and prints only what is whole on it.
// Each names the source it follows.

// meshPart is one volume of a synthetic PrusaSlicer 2.x object: a box, or a
// frustum, with its type.
type meshPart struct {
	kind   string
	lo, hi [3]float64
	// extruder is the extruder set on the volume, and 0 for none.
	extruder int
	// meta are more metadata elements of the volume.
	meta string
	// paint is written into the first triangle, and paintAll into every
	// triangle: attributes such as slic3rpe:mmu_segmentation="8".
	paint, paintAll string
}

// ps2Object is one object of a synthetic PrusaSlicer 2.x project, with the
// transform of each instance.
type ps2Object struct {
	name   string
	parts  []meshPart
	places []string
	// extruder is the extruder set on the object, and 0 for none.
	extruder int
	// meta are more metadata elements of the object, such as its own
	// settings.
	meta string
}

func boxPart(x0, y0, z0, x1, y1, z1 float64) meshPart {
	return meshPart{kind: "ModelPart", lo: [3]float64{x0, y0, z0}, hi: [3]float64{x1, y1, z1}}
}

func at(x, y float64) string { return fmt.Sprintf("1 0 0 0 1 0 0 0 1 %g %g 0", x, y) }

// ps2Project builds a project the way PrusaSlicer 2.x writes one: every
// volume of an object in one mesh, the volumes as runs of its triangles in
// Slic3r_PE_model.config, the first instance holding the mesh and every other
// one a component pointing at it.
func ps2Project(t *testing.T, app, bedShape string, height float64, objects ...ps2Object) []byte {
	t.Helper()

	return ps2ProjectWith(t, app, fmt.Sprintf(
		"; generated by PrusaSlicer 2.9.6\n; bed_shape = %s\n; max_print_height = %g\n",
		bedShape,
		height,
	), nil, objects...)
}

// ps2ProjectWith builds the project of ps2Project with the settings text
// config and more zip entries.
func ps2ProjectWith(t *testing.T, app, settings string, extra []entry, objects ...ps2Object) []byte {
	t.Helper()

	var res, build, config strings.Builder

	id := 1

	for _, o := range objects {
		var verts, tris, vols strings.Builder

		for p, part := range o.parts {
			base := 8 * p

			for i := range 8 {
				x, y, z := part.lo[0], part.lo[1], part.lo[2]
				if i&1 != 0 {
					x = part.hi[0]
				}

				if i&2 != 0 {
					y = part.hi[1]
				}

				if i&4 != 0 {
					z = part.hi[2]
				}

				fmt.Fprintf(&verts, `<vertex x="%g" y="%g" z="%g"/>`, x, y, z)
			}

			for n, tri := range [][3]int{
				{0, 2, 1}, {1, 2, 3}, {4, 5, 6}, {5, 7, 6}, {0, 1, 4}, {1, 5, 4},
				{2, 6, 3}, {3, 6, 7}, {0, 4, 2}, {2, 4, 6}, {1, 3, 5}, {3, 7, 5},
			} {
				paint := part.paintAll
				if n == 0 && part.paint != "" {
					paint = part.paint
				}

				fmt.Fprintf(
					&tris,
					`<triangle v1="%d" v2="%d" v3="%d" %s/>`,
					tri[0]+base,
					tri[1]+base,
					tri[2]+base,
					paint,
				)
			}

			extruder := part.meta
			if part.extruder != 0 {
				extruder += fmt.Sprintf(`<metadata type="volume" key="extruder" value="%d"/>`, part.extruder)
			}

			fmt.Fprintf(
				&vols,
				`<volume firstid="%d" lastid="%d"><metadata type="volume" key="volume_type" value="%s"/>%s</volume>`,
				12*p,
				12*p+11,
				part.kind,
				extruder,
			)
		}

		first := id
		fmt.Fprintf(
			&res,
			`<object id="%d" type="model"><mesh><vertices>%s</vertices><triangles>%s</triangles></mesh></object>`,
			id,
			verts.String(),
			tris.String(),
		)
		fmt.Fprintf(
			&config,
			`<object id="%d" instances_count="%d"><metadata type="object" key="name" value="%s"/>`+
				`<metadata type="object" key="extruder" value="%d"/>%s%s</object>`,
			id,
			len(o.places),
			o.name,
			o.extruder,
			o.meta,
			vols.String(),
		)

		for i, place := range o.places {
			if i > 0 {
				fmt.Fprintf(
					&res,
					`<object id="%d" type="model"><components><component objectid="%d"/></components></object>`,
					id,
					first,
				)
			}

			fmt.Fprintf(&build, `<item objectid="%d" transform="%s" printable="1"/>`, id, place)
			id++
		}
	}

	model := `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"` +
		` xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">`
	if app != "" {
		model += `<metadata name="Application">` + app + `</metadata>`
	}

	model += `<resources>` + res.String() + `</resources><build>` + build.String() + `</build></model>`

	entries := []entry{
		{"3D/3dmodel.model", model},
		{"Metadata/Slic3r_PE.config", settings},
		{
			"Metadata/Slic3r_PE_model.config",
			`<?xml version="1.0" encoding="UTF-8"?><config>` + config.String() + `</config>`,
		},
	}

	return zipOf(t, append(entries, extra...)...)
}

const (
	bedMK4  = "0x0,250x0,250x210,0x210"
	bedXL   = "0x0,360x0,360x360,0x360"
	bedMINI = "0x0,180x0,180x180,0x180"
)

func instanceAt(t *testing.T, p *threemf.Project, object int) threemf.Instance {
	t.Helper()

	if object >= len(p.Objects) || len(p.Objects[object].Instances) == 0 {
		t.Fatalf("no object %d", object)
	}

	return p.Objects[object].Instances[0]
}

// TestPS2GridOffsets pins MultipleBeds::get_bed_translation, bed_gap and
// BedsGrid::index2grid_coords of PrusaSlicer 2.9.0 to 2.9.6 (the functions are
// the same in every 2.9 release): a gap of min(100, 0.3 x the bed's diagonal)
// in both directions, beds in square shells, at most nine. A cube in the
// middle of bed 0, moved by the offset of bed b, is whole on bed b; moved by
// the offset the tenth bed would have, it is on no bed.
func TestPS2GridOffsets(t *testing.T) {
	t.Parallel()

	shells := [][2]int{{0, 0}, {1, 0}, {0, 1}, {1, 1}, {2, 0}, {2, 1}, {0, 2}, {1, 2}, {2, 2}, {3, 0}}

	for _, tc := range []struct {
		name  string
		shape string
		w, d  float64
	}{
		{"MK4", bedMK4, 250, 210},
		{"XL", bedXL, 360, 360},
		{"MINI", bedMINI, 180, 180},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			gap := math.Min(100, 0.3*math.Hypot(tc.w, tc.d))

			var objects []ps2Object

			for b, cell := range shells {
				x := float64(cell[0])*(tc.w+gap) + tc.w/2
				y := float64(cell[1])*(tc.d+gap) + tc.d/2
				objects = append(objects, ps2Object{
					name: fmt.Sprintf(
						"b%d",
						b,
					),
					parts:  []meshPart{boxPart(-5, -5, 0, 5, 5, 10)},
					places: []string{at(x, y)},
				})
			}

			p := read(t, ps2Project(t, "PrusaSlicer-2.9.6", tc.shape, 200, objects...))

			beds := p.Setups[0].Beds
			if len(beds) != 9 {
				t.Fatalf("%d beds, want 9", len(beds))
			}

			for b, cell := range shells {
				inst := instanceAt(t, p, b)
				if b == 9 {
					if inst.Bed != nil || inst.Placement != threemf.PlacementOutside {
						t.Errorf("a tenth bed: bed %v, %s", inst.Bed, inst.Placement)
					}

					continue
				}

				want := threemf.Point{X: float64(cell[0]) * (tc.w + gap), Y: float64(cell[1]) * (tc.d + gap)}
				if !near(beds[b].Offset.X, want.X) || !near(beds[b].Offset.Y, want.Y) {
					t.Errorf("bed %d offset %v, want %v", b, beds[b].Offset, want)
				}

				if inst.Bed == nil || inst.Bed.Bed != b || inst.Placement != threemf.PlacementInside {
					t.Errorf("cube of bed %d: bed %v, %s", b, inst.Bed, inst.Placement)
				}
			}
		})
	}
}

// TestPS2OffsetRoundTrip is a property test: any cube wholly on bed 0, moved
// by the offset of bed b, is wholly on bed b, and an instance's outline minus
// its bed's offset lies on bed 0.
func TestPS2OffsetRoundTrip(t *testing.T) {
	t.Parallel()

	rng := rand.New(rand.NewPCG(7, 11))
	gap := math.Min(100, 0.3*math.Hypot(250, 210))
	cells := [][2]int{{0, 0}, {1, 0}, {0, 1}, {1, 1}, {2, 0}, {2, 1}, {0, 2}, {1, 2}, {2, 2}}

	var objects []ps2Object

	type placed struct{ bed int }

	var want []placed

	for i := range 60 {
		side := 1 + rng.Float64()*40
		x := rng.Float64() * (250 - side)
		y := rng.Float64() * (210 - side)
		b := rng.IntN(9)
		x += float64(cells[b][0]) * (250 + gap)
		y += float64(cells[b][1]) * (210 + gap)
		objects = append(objects, ps2Object{
			name: fmt.Sprintf(
				"c%d",
				i,
			),
			parts:  []meshPart{boxPart(0, 0, 0, side, side, side)},
			places: []string{at(x, y)},
		})
		want = append(want, placed{bed: b})
	}

	p := read(t, ps2Project(t, "PrusaSlicer-2.9.6", bedMK4, 220, objects...))

	for o, w := range want {
		inst := instanceAt(t, p, o)
		if inst.Bed == nil || inst.Bed.Bed != w.bed || inst.Placement != threemf.PlacementInside {
			t.Errorf("cube %d: bed %v %s, want bed %d inside", o, inst.Bed, inst.Placement, w.bed)

			continue
		}

		off := p.Setups[0].Beds[w.bed].Offset
		for _, pt := range inst.Outline {
			if x, y := pt.X-off.X, pt.Y-off.Y; x < -1e-9 || x > 250+1e-9 || y < -1e-9 || y > 210+1e-9 {
				t.Errorf("cube %d: outline point %v is off bed 0 after the offset", o, pt)
			}
		}
	}
}

// TestPS2VertexRule pins BuildVolume::object_state of 2.9.6: a part is on a bed
// when one of its vertices is, not when its outline crosses the bed. A bar
// longer than the bed, laid across it with its ends outside, has no vertex on
// the bed, so the slicer puts it on no bed and shows it wholly outside.
func TestPS2VertexRule(t *testing.T) {
	t.Parallel()

	p := read(t, ps2Project(t, "PrusaSlicer-2.9.6", bedMK4, 220,
		ps2Object{name: "bar", parts: []meshPart{boxPart(-25, 0, 0, 275, 10, 10)}, places: []string{at(0, 100)}},
		ps2Object{name: "stub", parts: []meshPart{boxPart(-25, 0, 0, 25, 10, 10)}, places: []string{at(0, 150)}},
	))

	if bar := instanceAt(t, p, 0); bar.Bed != nil || bar.Placement != threemf.PlacementOutside {
		t.Errorf("bar across the bed: bed %v, %s; want no bed, outside", bar.Bed, bar.Placement)
	}

	if stub := instanceAt(
		t,
		p,
		1,
	); stub.Bed == nil || stub.Bed.Bed != 0 ||
		stub.Placement != threemf.PlacementPartlyOutside {
		t.Errorf("stub over the edge: bed %v, %s; want bed 0, partly outside", stub.Bed, stub.Placement)
	}
}

// TestPS2FirstPartWithABed pins ModelObject::update_instances_print_volume_state
// of 2.9.6: the instance takes the bed of the first model part that is on a
// bed, a modifier does not count, and each part is judged on its own bed, so
// an object with one part whole on bed 0 and one whole on bed 1 is inside.
func TestPS2FirstPartWithABed(t *testing.T) {
	t.Parallel()

	modifier := boxPart(400, 0, 0, 410, 10, 10)
	modifier.kind = "ParameterModifier"

	p := read(t, ps2Project(
		t,
		"PrusaSlicer-2.9.6",
		bedMK4,
		220,
		ps2Object{
			name:   "split",
			parts:  []meshPart{boxPart(400, 0, 0, 410, 10, 10), boxPart(0, 0, 0, 10, 10, 10)},
			places: []string{at(30, 30)},
		},
		ps2Object{
			name:   "lost",
			parts:  []meshPart{boxPart(-2000, 0, 0, -1990, 10, 10), boxPart(0, 0, 0, 10, 10, 10)},
			places: []string{at(30, 60)},
		},
		ps2Object{
			name:   "modifier",
			parts:  []meshPart{modifier, boxPart(0, 0, 0, 10, 10, 10)},
			places: []string{at(30, 90)},
		},
	))

	checks := []struct {
		bed       int
		placement threemf.Placement
	}{
		{1, threemf.PlacementInside},
		{0, threemf.PlacementPartlyOutside},
		{0, threemf.PlacementInside},
	}

	for o, want := range checks {
		inst := instanceAt(t, p, o)
		if inst.Bed == nil || inst.Bed.Bed != want.bed || inst.Placement != want.placement {
			t.Errorf(
				"%s: bed %v, %s; want bed %d, %s",
				p.Objects[o].Name,
				inst.Bed,
				inst.Placement,
				want.bed,
				want.placement,
			)
		}
	}
}

// TestPS2HeightOnOpen pins ModelObject::ensure_on_bed(true), which 2.9.6 runs
// on every object when it opens a project: an object of one part is put on
// the bed unless it sinks into it, so a part floating above the bed, or wholly
// below it, is judged where the slicer puts it. An object of several parts
// keeps its height.
func TestPS2HeightOnOpen(t *testing.T) {
	t.Parallel()

	p := read(t, ps2Project(t, "PrusaSlicer-2.9.6", bedMK4, 220,
		ps2Object{name: "floating", parts: []meshPart{boxPart(0, 0, 10, 10, 10, 225)}, places: []string{at(20, 20)}},
		ps2Object{name: "buried", parts: []meshPart{boxPart(0, 0, -30, 10, 10, -20)}, places: []string{at(400, 20)}},
		ps2Object{name: "sinking", parts: []meshPart{boxPart(0, 0, -5, 10, 10, 5)}, places: []string{at(60, 20)}},
		ps2Object{name: "two parts above", parts: []meshPart{
			boxPart(0, 0, 10, 10, 10, 225), boxPart(20, 0, 10, 30, 10, 20),
		}, places: []string{at(100, 20)}},
	))

	checks := []struct {
		bed       int
		placement threemf.Placement
	}{
		{0, threemf.PlacementInside},
		{1, threemf.PlacementInside},
		{0, threemf.PlacementInside},
		{0, threemf.PlacementPartlyOutside},
	}

	for o, want := range checks {
		inst := instanceAt(t, p, o)
		if inst.Bed == nil || inst.Bed.Bed != want.bed || inst.Placement != want.placement {
			t.Errorf(
				"%s: bed %v, %s; want bed %d, %s",
				p.Objects[o].Name,
				inst.Bed,
				inst.Placement,
				want.bed,
				want.placement,
			)
		}
	}
}

// TestPS2BedCount pins MultipleBeds::update_shown_beds: the beds are those up
// to the highest one used, an empty bed between them included.
func TestPS2BedCount(t *testing.T) {
	t.Parallel()

	gap := math.Min(100, 0.3*math.Hypot(250, 210))

	p := read(t, ps2Project(
		t,
		"PrusaSlicer-2.9.6",
		bedMK4,
		220,
		ps2Object{
			name:   "a",
			parts:  []meshPart{boxPart(0, 0, 0, 10, 10, 10)},
			places: []string{at(20, 20), at(250+gap+20, 210+gap+20)},
		},
	))

	beds := p.Setups[0].Beds
	if len(beds) != 4 || len(beds[1].Instances) != 0 || len(beds[2].Instances) != 0 || len(beds[3].Instances) != 1 {
		t.Errorf("beds %+v, want 4 with bed 2 and 3 empty but the last", beds)
	}
}

// TestPS2LegacyRowNeedsPrusaSlicer pins Plater::priv::load_files of 2.9.6: the
// row of the releases before 2.9 is tried only for a model whose Application
// is PrusaSlicer-<version> below 2.9.0-alpha1. A project laid out on the row,
// written by any other program or by 2.9.0-alpha1, is read on the grid.
func TestPS2LegacyRowNeedsPrusaSlicer(t *testing.T) {
	t.Parallel()

	row := 250 * 1.2
	objects := []ps2Object{
		{name: "a", parts: []meshPart{boxPart(0, 0, 0, 10, 10, 10)}, places: []string{at(20, 20), at(row+20, 20)}},
	}

	for _, tc := range []struct {
		app    string
		offset float64
	}{
		{"PrusaSlicer-2.8.1", row},
		{"PrusaSlicer-2.9.0-alpha0", row},
		{"PrusaSlicer-2.9.0-alpha1", 250 + math.Min(100, 0.3*math.Hypot(250, 210))},
		{"Slic3r PE-1.41.3", 250 + math.Min(100, 0.3*math.Hypot(250, 210))},
		{"", 250 + math.Min(100, 0.3*math.Hypot(250, 210))},
	} {
		p := read(t, ps2Project(t, tc.app, bedMK4, 220, objects...))

		beds := p.Setups[0].Beds
		second := p.Objects[0].Instances[1]

		if tc.offset == row {
			if len(beds) != 2 || !near(beds[1].Offset.X, row) || second.Bed == nil || second.Bed.Bed != 1 {
				t.Errorf("%q: beds %+v, second on %v; want the row", tc.app, beds, second.Bed)
			}

			continue
		}

		// On the grid the second cube stands in the gap after bed 0, on no bed.
		if len(beds) != 1 || second.Bed != nil {
			t.Errorf("%q: beds %+v, second on %v; want the grid", tc.app, beds, second.Bed)
		}
	}
}

// TestPS2NozzlesPerHotEnd checks that a printer that feeds several filaments
// into one hot end has one nozzle, while a printer with several tools has one
// per tool. PrusaSlicer writes a nozzle_diameter for every extruder, and an
// MMU is one extruder per filament.
func TestPS2NozzlesPerHotEnd(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct {
		name, semm, nozzles string
		want                int
	}{
		{"MK4S MMU3", "1", "0.4,0.4,0.4,0.4,0.4", 1},
		{"XL 5T", "0", "0.4,0.4,0.4,0.4,0.6", 5},
		{"CORE One with 8 tools", "0", "0.4,0.4,0.4,0.4,0.4,0.4,0.4,0.4", 8},
		{"no flag", "", "0.4,0.4", 2},
	} {
		config := "; bed_shape = " + bedMK4 + "\n; nozzle_diameter = " + tc.nozzles +
			"\n; nozzle_high_flow = 1,0,0,0,0,0,0,0\n"
		if tc.semm != "" {
			config += "; single_extruder_multi_material = " + tc.semm + "\n"
		}

		p := read(t, zipOf(t,
			entry{"3D/3dmodel.model", `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
 <metadata name="Application">PrusaSlicer-2.9.6</metadata>
 <resources><object id="1" type="model">` + box(10, 10, 10) + `</object></resources>
 <build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 20 20 0"/></build>
</model>`},
			entry{"Metadata/Slic3r_PE.config", config},
		))

		nozzles := p.Setups[0].Nozzles
		if len(nozzles) != tc.want || nozzles[0].HighFlow == nil || !*nozzles[0].HighFlow {
			t.Errorf("%s: nozzles %+v, want %d with the first high-flow", tc.name, nozzles, tc.want)
		}
	}
}
