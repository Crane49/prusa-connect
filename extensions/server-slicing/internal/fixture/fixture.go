// Package fixture writes small 3MF projects for the tests: one 10 mm cube,
// placed once at each point, in the shape PrusaSlicer 2.9 saves a project.
package fixture

import (
	"archive/zip"
	"bytes"
	"fmt"
	"strings"
)

// Project describes one project to write.
type Project struct {
	// At is where each copy of the cube stands, one build item each.
	At [][2]float64
	// Settings are lines of Metadata/Slic3r_PE.config, such as
	// "bed_shape = 0x0,200x0,200x200,0x200". None writes no settings file.
	Settings []string
	// Mode is a word the stand-in slicer reads to know what to do. It is
	// stored uncompressed, so the stand-in finds it with grep.
	Mode string
	// Application is the program the model names as its writer. Empty is
	// PrusaSlicer-2.9.6.
	Application string
	// Plain leaves out the metadata a slicer writes into the model, so the
	// project reads as one another program saved. PrusaSlicer then takes
	// its own defaults for every setting the project does not name.
	Plain bool
}

// Bed200 is the settings of a printer with a 200 by 200 mm bed whose G-code
// labels each object. Its beds are 284.85 mm apart: a gap of 0.3 times the
// diagonal, as PrusaSlicer 2.9 lays beds out on a grid.
var Bed200 = []string{
	"printer_technology = FFF",
	"bed_shape = 0x0,200x0,200x200,0x200",
	"max_print_height = 200",
	"gcode_label_objects = firmware",
}

// Bed1X is where the second bed of Bed200 starts.
const Bed1X = 284.85

// Bytes writes the project as a 3MF file.
func (p Project) Bytes() ([]byte, error) {
	var buffer bytes.Buffer

	writer := zip.NewWriter(&buffer)

	entries := []struct{ name, body string }{
		{"[Content_Types].xml", contentTypes},
		{"_rels/.rels", relationships},
		{"3D/3dmodel.model", p.model()},
	}

	if len(p.Settings) > 0 {
		entries = append(entries, struct{ name, body string }{
			"Metadata/Slic3r_PE.config",
			"; generated by PrusaSlicer 2.9.6\n; " + strings.Join(p.Settings, "\n; ") + "\n",
		})
	}

	for _, entry := range entries {
		file, err := writer.Create(entry.name)
		if err != nil {
			return nil, err
		}

		if _, err = file.Write([]byte(entry.body)); err != nil {
			return nil, err
		}
	}

	if p.Mode != "" {
		marker, err := writer.CreateHeader(&zip.FileHeader{Name: "Metadata/mode.txt", Method: zip.Store})
		if err != nil {
			return nil, err
		}

		if _, err = marker.Write([]byte("mode:" + p.Mode)); err != nil {
			return nil, err
		}
	}

	if err := writer.Close(); err != nil {
		return nil, err
	}

	return buffer.Bytes(), nil
}

func (p Project) model() string {
	const half = 5.0

	application := p.Application
	if application == "" {
		application = "PrusaSlicer-2.9.6"
	}

	var mesh strings.Builder

	mesh.WriteString("<mesh><vertices>")

	for _, z := range []float64{0, 2 * half} {
		for _, y := range []float64{-half, half} {
			for _, x := range []float64{-half, half} {
				fmt.Fprintf(&mesh, `<vertex x="%g" y="%g" z="%g"/>`, x, y, z)
			}
		}
	}

	mesh.WriteString("</vertices><triangles>")

	for _, tri := range [][3]int{
		{0, 2, 1}, {1, 2, 3}, {4, 5, 6}, {5, 7, 6}, {0, 1, 4}, {1, 5, 4},
		{2, 6, 3}, {3, 6, 7}, {0, 4, 2}, {2, 4, 6}, {1, 3, 5}, {3, 7, 5},
	} {
		fmt.Fprintf(&mesh, `<triangle v1="%d" v2="%d" v3="%d"/>`, tri[0], tri[1], tri[2])
	}

	mesh.WriteString("</triangles></mesh>")

	var build strings.Builder
	for _, point := range p.At {
		fmt.Fprintf(&build, `<item objectid="1" transform="1 0 0 0 1 0 0 0 1 %g %g 0" printable="1"/>`,
			point[0], point[1])
	}

	metadata := `<metadata name="slic3rpe:Version3mf">1</metadata><metadata name="Application">` + application + `</metadata>`
	if p.Plain {
		metadata = ""
	}

	return `<?xml version="1.0" encoding="UTF-8"?>` +
		`<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02" ` +
		`xmlns:slic3rpe="http://schemas.slic3r.org/3mf/2017/06">` + metadata +
		`<resources><object id="1" type="model">` + mesh.String() + `</object></resources>` +
		`<build>` + build.String() + `</build></model>`
}

const contentTypes = `<?xml version="1.0" encoding="UTF-8"?>` +
	`<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
	`<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>` +
	`<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>`

const relationships = `<?xml version="1.0" encoding="UTF-8"?>` +
	`<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">` +
	`<Relationship Target="/3D/3dmodel.model" Id="rel-1" ` +
	`Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>`
