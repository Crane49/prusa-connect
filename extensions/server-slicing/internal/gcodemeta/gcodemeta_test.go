const objectsInfo = `{"objects":[{"name":"Cube (Instance 1)","polygon":[[105.0,105.0],[95.0,105.0],[95.0,95.0]]},` +
	`{"name":"Cube (Instance 2)","polygon":[[135.0,105.0],[125.0,105.0],[125.0,95.0]]}]}`

// block writes one block of a binary G-code file, with its checksum.
func block(kind, compression uint16, params, data []byte, unpackedSize int) []byte {
	var out bytes.Buffer

	_ = binary.Write(&out, binary.LittleEndian, kind)
	_ = binary.Write(&out, binary.LittleEndian, compression)
	_ = binary.Write(&out, binary.LittleEndian, uint32(unpackedSize))

	if compression != 0 {
		_ = binary.Write(&out, binary.LittleEndian, uint32(len(data)))
	}

	out.Write(params)
	out.Write(data)

	_ = binary.Write(&out, binary.LittleEndian, crc32.ChecksumIEEE(out.Bytes()))

	return out.Bytes()
}

func deflated(text string) []byte {
	var out bytes.Buffer

	writer := zlib.NewWriter(&out)
	_, _ = writer.Write([]byte(text))
	_ = writer.Close()

	return out.Bytes()
}

func write(t *testing.T, name string, data []byte) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}

	return path
}

func TestABinaryFileIsReadFromItsMetadataBlocks(t *testing.T) {
	t.Parallel()

	var file bytes.Buffer

	file.WriteString("GCDE")
	_ = binary.Write(&file, binary.LittleEndian, uint32(1))
	_ = binary.Write(&file, binary.LittleEndian, uint16(1))

	ini := []byte{0, 0}
	printer := "printer_model=MK4S\nfilament_type=PETG;PLA\nnozzle_diameter=0.4,0.6\nobjects_info=" + objectsInfo + "\n"
	printMeta := "filament used [mm]=853.03, 10\nfilament used [g]=2.5\nestimated printing time (normal mode)=1h 17m 49s\n"

	file.Write(block(0, 0, ini, []byte("Producer=PrusaSlicer 2.9.6\n"), 27))
	file.Write(block(3, 0, ini, []byte(printer), len(printer)))
	file.Write(block(5, 0, []byte{0, 0, 16, 0, 16, 0}, []byte("png bytes"), 9))
	file.Write(block(5, 0, []byte{2, 0, 220, 0, 124, 0}, []byte("qoi bytes"), 9))
	file.Write(block(4, 1, ini, deflated(printMeta), len(printMeta)))
	file.Write(block(1, 3, []byte{2, 0}, []byte("packed G-code"), 100))

	meta, err := gcodemeta.Read(write(t, "part.bgcode", file.Bytes()))
	if err != nil {
		t.Fatal(err)
	}

	if meta.PrinterModel != "MK4S" || meta.FilamentType != "PETG" || meta.NozzleMM != 0.4 {
		t.Errorf("the printer metadata read as %+v", meta)
	}

	if meta.EstimatedSeconds != 3600+17*60+49 || meta.FilamentG != 2.5 || meta.FilamentMM != 863.03 {
		t.Errorf("the print metadata read as %+v", meta)
	}

	if meta.Producer != "PrusaSlicer 2.9.6" {
		t.Errorf("the producer read as %q", meta.Producer)
	}

	if len(meta.Objects) != 2 || meta.Objects[1].ID != 1 || meta.Objects[1].Name != "Cube (Instance 2)" ||
		len(meta.Objects[1].Polygon) != 3 || meta.Objects[1].Polygon[0].X != 135 {
		t.Errorf("the objects read as %+v", meta.Objects)
	}

	if len(meta.Thumbnails) != 2 ||
		meta.Thumbnails[1] != (gcodemeta.Thumbnail{Format: "qoi", Width: 220, Height: 124}) {
		t.Errorf("the pictures read as %+v", meta.Thumbnails)
	}
}

func TestATextFileIsReadAtItsHeadAndItsTail(t *testing.T) {
	t.Parallel()

	var file strings.Builder

	file.WriteString("; generated by PrusaSlicer 3.0.0-alpha12 on 2026-10-26 at 22:52:17 UTC\n")
	file.WriteString("; thumbnail begin 16x16 100\n; aGVsbG8=\n; thumbnail end\n")
	file.WriteString("; thumbnail_QOI begin 220x124 100\n; aGVsbG8=\n; thumbnail_QOI end\n")

	// More G-code than one window, so the tail is read apart from the head.
	for range 120_000 {
		file.WriteString("G1 X10.000 Y10.000 E0.0100\n")
	}

	file.WriteString("; objects_info = " + objectsInfo + "\n")
	file.WriteString("; filament used [g] = 1.25\n; estimated printing time (normal mode) = 7m 47s\n")
	file.WriteString("; printer_model = COREONE\n")

	meta, err := gcodemeta.Read(write(t, "part.gcode", []byte(file.String())))
	if err != nil {
		t.Fatal(err)
	}

	if meta.Producer != "PrusaSlicer 3.0.0-alpha12" || meta.EstimatedSeconds != 467 || meta.FilamentG != 1.25 ||
		meta.PrinterModel != "COREONE" {
		t.Errorf("the file read as %+v", meta)
	}

	if len(meta.Objects) != 2 || len(meta.Thumbnails) != 2 || meta.Thumbnails[1].Format != "qoi" {
		t.Errorf("the objects and pictures read as %+v %+v", meta.Objects, meta.Thumbnails)
	}
}

func TestAFileWithNothingInItReadsAsEmpty(t *testing.T) {
	t.Parallel()

	meta, err := gcodemeta.Read(write(t, "bare.gcode", []byte("G28\nG1 X1\n")))
	if err != nil {
		t.Fatal(err)
	}

	if meta.EstimatedSeconds != 0 || len(meta.Objects) != 0 || meta.Objects == nil {
		t.Fatalf("a bare file read as %+v", meta)
	}
}
