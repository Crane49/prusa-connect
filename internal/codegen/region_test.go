package codegen_test

import (
	"errors"
	"strings"
	"testing"

	"github.com/prusa3d/prusa-connect/internal/codegen"
)

var page = codegen.Region{
	Start: "<!-- generated by make thing for ",
	End:   "<!-- end generated -->",
}

// TestSpliceReplacesOnlyTheRegion is the promise a person relies on: the
// bytes before the opening marker and after the closing one are the same
// after a run, whatever the region held.
func TestSpliceReplacesOnlyTheRegion(t *testing.T) {
	t.Parallel()

	region := page.Wrap("the x tag", "regenerate.", "new body")
	committed := []byte("head\n\n" + string(page.Wrap("the x tag", "regenerate.", "old body")) + "\n\ntail\n")

	got, err := page.Splice(committed, region)
	if err != nil {
		t.Fatalf("Splice() error = %v", err)
	}

	want := "head\n\n" + string(region) + "\n\ntail\n"
	if string(got) != want {
		t.Errorf("Splice() = %q, want %q", got, want)
	}

	prose, err := page.HandWritten(got)
	if err != nil {
		t.Fatalf("HandWritten() error = %v", err)
	}

	if prose != "head\n\n\n\ntail\n" {
		t.Errorf("HandWritten() = %q", prose)
	}

	if !strings.HasPrefix(string(region), page.Start+"the x tag. Do not edit: regenerate. -->\n\n") {
		t.Errorf("the opening marker does not read as a sentence: %q", region)
	}
}

// TestAPageWithoutItsMarkersIsRefused covers the two ways a person can break
// the protocol: removing a marker, and putting the closing one first.
func TestAPageWithoutItsMarkersIsRefused(t *testing.T) {
	t.Parallel()

	region := page.Wrap("the x tag", "regenerate.", "body")

	if _, err := page.Splice([]byte("no markers\n"), region); !errors.Is(err, codegen.ErrNoRegion) {
		t.Errorf("a page with no markers was spliced: %v", err)
	}

	reversed := []byte(page.End + "\n" + page.Start + "x -->\n")
	if _, err := page.Splice(reversed, region); !errors.Is(err, codegen.ErrNoRegion) {
		t.Errorf("markers in the wrong order were spliced: %v", err)
	}

	if _, err := page.HandWritten([]byte("no markers\n")); !errors.Is(err, codegen.ErrNoRegion) {
		t.Errorf("a page with no markers has hand-written prose: %v", err)
	}
}
