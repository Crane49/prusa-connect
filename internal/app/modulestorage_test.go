// A named refusal of the storage plane and what a module should read for it.
type storageRefusalCase struct {
	name   string
	raised error
}

// settledRefusals are the failures that will read the same on the next call.
// The storage in each one is named "secret-nas" and the path is this server's
// own, so a test can require that neither reaches the module.
func settledRefusals() []storageRefusalCase {
	return []storageRefusalCase{
		{"the storage is not declared", fault.StorageNotFound.
			New("no storage of that name is serving").
			With(fault.StringParam("storage_id", "secret-nas")).
			Wrap(ErrNoSuchStorage)},
		{"the storage holds no such file", fault.StorageFileNotFound.
			New("the storage holds no file under that name").
			With(fault.StringParam("storage_id", "secret-nas"))},
		{"the path leaves the storage", fault.StorageInvalidPath.
			New("the path leaves the storage it names").
			With(fault.StringParam("storage_id", "secret-nas"))},
		{"the storage will not read the file", fault.StorageNotReadable.
			New("open /srv/storages/secret-nas/part.gcode: permission denied").
			With(fault.StringParam("storage_id", "secret-nas"))},
		{"this server cannot read the file", fmt.Errorf(
			"%w: open /srv/storages/secret-nas/part.gcode: permission denied", ErrStorageCannotRead)},
	}
}

// passingRefusals are the failures a module may meet again and find gone.
func passingRefusals() []storageRefusalCase {
	return []storageRefusalCase{
		{"the storage is not running", fault.StorageUnavailable.
			New("the storage resource is not serving").
			With(fault.StringParam("storage_id", "secret-nas"))},
		{"the call was cancelled", context.Canceled},
		{"the call ran out of time", context.DeadlineExceeded},
		{"the provider failed", errors.New(
			"open /srv/storages/secret-nas/part.gcode: permission denied")},
	}
}

// A file that is settled as out of reach is one sentence, whichever of the
// five reasons it was. A module takes such a file off its list, so the answer
// has to mean what it says, and the sentence carries no storage name and no
// path of this server's own.
func TestASettledStorageFailureReachesAModuleAsOneSentence(t *testing.T) {
	t.Parallel()

	files := moduleStorage{standing: moduleStanding{principal: readingModule}}
	want := files.refusal(t.Context(), settledRefusals()[0].raised).Error()

	for _, refusal := range settledRefusals() {
		t.Run(refusal.name, func(t *testing.T) {
			t.Parallel()

			answered := files.refusal(t.Context(), refusal.raised)

			require.ErrorIs(t, answered, storageapi.ErrNoFile)
			require.NotContains(t, answered.Error(), "secret-nas",
				"the answer names the storage the module asked about")
			require.NotContains(t, answered.Error(), "/srv/",
				"the answer carries a path of this server's own")
			require.Equal(t, want, answered.Error(), "one failure reads differently from another")
		})
	}
}

// A failure that may be gone on the next call is a second sentence, and never
// the one that says the file is not there. A module told a file is absent
// takes it off its list, and a storage that is down for a minute would empty
// that list.
func TestAPassingStorageFailureNeverReadsAsAnAbsentFile(t *testing.T) {
	t.Parallel()

	files := moduleStorage{standing: moduleStanding{principal: readingModule}}
	want := files.refusal(t.Context(), passingRefusals()[0].raised).Error()

	for _, refusal := range passingRefusals() {
		t.Run(refusal.name, func(t *testing.T) {
			t.Parallel()

			answered := files.refusal(t.Context(), refusal.raised)

			require.ErrorIs(t, answered, storageapi.ErrUnreadable)
			require.NotErrorIs(t, answered, storageapi.ErrNoFile,
				"a storage that may answer next time was reported as a file that is not there")
			require.NotContains(t, answered.Error(), "secret-nas",
				"the answer names the storage the module asked about")
			require.NotContains(t, answered.Error(), "/srv/",
				"the answer carries a path of this server's own")
			require.Equal(t, want, answered.Error(), "one failure reads differently from another")
		})
	}
}

// countingStorages is the storage plane with a tally of the two reads a module
// makes of one file, so a test can say which one a chunked read took.
type countingStorages struct {
	httpapi.Storages

	stats   atomic.Int64
	extents atomic.Int64
}

func (c *countingStorages) Stat(
	ctx context.Context, principal string, storage string, path string,
) (httpapi.StorageEntry, error) {
	c.stats.Add(1)

	return c.Storages.Stat(ctx, principal, storage, path)
}

func (c *countingStorages) FileExtent(
	ctx context.Context, principal string, storage string, path string,
) (httpapi.FileExtent, error) {
	c.extents.Add(1)

	return c.Storages.FileExtent(ctx, principal, storage, path)
}

// A module walking a file asks for its length on every piece and never for the
// description. Stat opens the file and parses the head of it to say what the
// slicer wrote, and a walk of a large file would pay for that parse once per
// piece.
func TestAChunkedReadNeverAsksForTheFilesDescription(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	counted := &countingStorages{Storages: files.stores}
	files.stores = counted

	var offset int64

	for range 20 {
		chunk, err := files.Read(t.Context(), storageapi.ReadParams{
			Storage: "bench", Path: "part.gcode", Offset: offset, Length: 16,
		})
		require.NoError(t, err)

		offset += int64(len(chunk.Data))

		if chunk.EOF {
			break
		}
	}

	require.Equal(t, int64(len(gcodeSample)), offset, "the walk did not read the whole file")
	require.Zero(t, counted.stats.Load(),
		"a chunked read parsed the print file once per piece")
	require.Positive(t, counted.extents.Load(), "the read asked for no length at all")
}

// A module's own write is held to its ceiling and then to the graph, and one
// inside both publishes the file. Both directions of the same rule.
func TestAModuleWritesOnlyWhatItWasGranted(t *testing.T) {
	t.Parallel()

	params := storageapi.WriteParams{Storage: "bench", Path: "out/part.bgcode", Size: 5}

	// Outside the ceiling: the graph grant does not help.
	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelOperator, readingModule)))

	_, err := files.Write(t.Context(), params, strings.NewReader("hello"))
	require.ErrorIs(t, err, storageapi.ErrDenied)

	// Inside the ceiling and with no grant: refused.
	files, graph = storageForModule(t, authz.ActionWriteStorage)

	_, err = files.Write(t.Context(), params, strings.NewReader("hello"))
	require.ErrorIs(t, err, storageapi.ErrDenied)

	// Inside both: published, and the answer carries the digest.
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelOperator, readingModule)))

	written, err := files.Write(t.Context(), params, strings.NewReader("hello"))
	require.NoError(t, err)
	require.Equal(t, int64(5), written.Size)
	require.Equal(t, "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824", written.SHA256)
}

// A body that fails partway publishes nothing, so the file that was there
// before is still the one a reader gets.
func TestAModuleWriteThatFailsPartwayKeepsTheOldFile(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionWriteStorage, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelOperator, readingModule)))

	broken := io.MultiReader(strings.NewReader("G1 X1"), iotest.ErrReader(storageapi.ErrShortWrite))

	_, err := files.Write(t.Context(),
		storageapi.WriteParams{Storage: "bench", Path: "part.gcode", Size: 100}, broken)
	require.ErrorIs(t, err, storageapi.ErrShortWrite)

	chunk, err := files.Read(t.Context(), storageapi.ReadParams{Storage: "bench", Path: "part.gcode"})
	require.NoError(t, err)
	require.Equal(t, gcodeSample, chunk.Data)
}

// A listing gives each entry's name, whether it is a folder, a file's size,
// the time it changed and the digest the storage kept, in the order of the
// names. A file nobody wrote through the storage has no digest.
func TestAModuleListsAFolder(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	changed := time.Date(2026, 10, 23, 9, 0, 0, 0, time.UTC)

	require.NoError(t, os.WriteFile(filepath.Join(root, "part.gcode"), gcodeSample, 0o600))
	require.NoError(t, os.Mkdir(filepath.Join(root, "models"), 0o700))

	for _, name := range []string{"part.gcode", "models"} {
		require.NoError(t, os.Chtimes(filepath.Join(root, name), changed, changed))
	}

	files, graph := storageOver(t, root, authz.ActionReadStorage)
	grantReading(t, graph)

	listing, err := files.List(t.Context(), storageapi.ListParams{Storage: "bench"})
	require.NoError(t, err)
	require.Equal(t, storageapi.Listing{Entries: []storageapi.ListEntry{
		{Name: "models", Dir: true, MTime: changed.Unix()},
		{Name: "part.gcode", Size: int64(len(gcodeSample)), MTime: changed.Unix()},
	}}, listing)
}

// A folder over the bound is answered in pages of MaxListEntries, and the
// cursor of each page leads to the next one.
func TestAModuleListsALargeFolderInPages(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	want := make([]string, 0, storageapi.MaxListEntries+1)

	for i := range storageapi.MaxListEntries + 1 {
		name := fmt.Sprintf("part-%04d.gcode", i)
		require.NoError(t, os.WriteFile(filepath.Join(root, name), []byte("G28\n"), 0o600))

		want = append(want, name)
	}

	files, graph := storageOver(t, root, authz.ActionReadStorage)
	grantReading(t, graph)

	first, err := files.List(t.Context(), storageapi.ListParams{Storage: "bench"})
	require.NoError(t, err)

	second, err := files.List(t.Context(), storageapi.ListParams{Storage: "bench", Cursor: first.Next})
	require.NoError(t, err)

	last := storageapi.MaxListEntries
	require.Equal(t,
		[][]string{want[:last], want[last:]},
		[][]string{namesOf(first), namesOf(second)})
	require.Equal(t, []string{want[last-1], ""}, []string{first.Next, second.Next})
}

// A listing takes what a read takes: the ceiling first, then the graph, and a
// call for a person is decided for that person.
func TestAListTakesWhatAReadTakes(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)

	_, err := files.List(t.Context(), storageapi.ListParams{Storage: "bench"})
	require.ErrorIs(t, err, storageapi.ErrDenied, "the graph gave the module nothing")

	grantReading(t, graph)

	_, err = files.List(t.Context(), storageapi.ListParams{Principal: "user:beta", Storage: "bench"})
	require.ErrorIs(t, err, storageapi.ErrDenied, "the person holds nothing on the storage kind")

	outside, outsideGraph := storageForModule(t, authz.ActionObserve)
	grantReading(t, outsideGraph)

	_, err = outside.List(t.Context(), storageapi.ListParams{Storage: "bench"})
	require.ErrorIs(t, err, storageapi.ErrDenied, "the ceiling holds no read_storage")
}

