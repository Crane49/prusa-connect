// readingModule is the instance every case here reads as.
const readingModule = "sink:filament"

// gcodeSample is what the storage holds. It is long enough that a read of the
// whole file takes more than one call at the size these cases ask for.
var gcodeSample = []byte(
	"; generated by a slicer\n; filament_type = PETG\nG28\nG1 X10 Y10\n; filament used [g] = 12.4\n")

// storageForModule is a module's view of one storage holding one file and one
// folder, with the ceiling the operator wrote for the instance.
func storageForModule(t *testing.T, ceiling ...authz.Action) (moduleStorage, *authz.Store) {
	t.Helper()

	root := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(root, "part.gcode"), gcodeSample, 0o600))
	require.NoError(t, os.Mkdir(filepath.Join(root, "models"), 0o700))

	return storageOver(t, root, ceiling...)
}

// storageOver is a module's view of the storage "bench" over root.
func storageOver(t *testing.T, root string, ceiling ...authz.Action) (moduleStorage, *authz.Store) {
	t.Helper()

	graph := newGraph(t)
	plane := storagePlane{graph: graph, stores: stores{host: stageOne(t, root).host}}

	return moduleStorage{
		stores:   plane,
		standing: moduleStanding{principal: readingModule, ceiling: ceiling},
	}, graph
}

// grantReading gives the reading module read_storage on the storage kind.
func grantReading(t *testing.T, graph *authz.Store) {
	t.Helper()

	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))
}

// namesOf is the names of a page, in its order.
func namesOf(listing storageapi.Listing) []string {
	names := make([]string, 0, len(listing.Entries))
	for _, entry := range listing.Entries {
		names = append(names, entry.Name)
	}

	return names
}

// A module's own read is held to its ceiling first. An instance the operator
// installed without read_storage reads nothing, whatever the graph says.
func TestAModulesOwnReadIsHeldToItsCeiling(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionObserve)

	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	_, err := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: "part.gcode"})
	require.ErrorIs(t, err, storageapi.ErrDenied)

	_, err = files.Read(t.Context(), storageapi.ReadParams{Storage: "bench", Path: "part.gcode"})
	require.ErrorIs(t, err, storageapi.ErrDenied)
}

// A module inside its ceiling and granted read_storage reads the file, and one
// the graph gave nothing is refused. Both directions of the same rule.
func TestAModuleReadsAFileItWasGrantedAndNotOneItWasNot(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)

	// The refusal. The ceiling names read_storage and the graph holds no
	// grant for this instance.
	_, err := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: "part.gcode"})
	require.ErrorIs(t, err, storageapi.ErrDenied)

	// The permit.
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	info, err := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: "part.gcode"})
	require.NoError(t, err)
	require.Equal(t, int64(len(gcodeSample)), info.Size)
	require.False(t, info.IsDir)
	require.NotZero(t, info.MTime)
}

// A read of a whole file walks it with the offset, and the last piece says it
// reached the end, so a module stops without a call that answers nothing.
func TestAModuleWalksAFileWithTheOffset(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	var (
		held   []byte
		offset int64
	)

	for range 20 {
		chunk, err := files.Read(t.Context(), storageapi.ReadParams{
			Storage: "bench", Path: "part.gcode", Offset: offset, Length: 16,
		})
		require.NoError(t, err)

		held = append(held, chunk.Data...)
		offset += int64(len(chunk.Data))

		require.Equal(t, int64(len(gcodeSample)), chunk.Size)

		if chunk.EOF {
			break
		}
	}

	require.Equal(t, gcodeSample, held)
}

// A read past the end of a file answers no bytes and says so, rather than
// failing.
func TestAReadPastTheEndOfAFileIsEmptyAndDone(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	chunk, err := files.Read(t.Context(), storageapi.ReadParams{
		Storage: "bench", Path: "part.gcode", Offset: int64(len(gcodeSample)) + 100,
	})
	require.NoError(t, err)
	require.Empty(t, chunk.Data)
	require.True(t, chunk.EOF)
	require.Equal(t, int64(len(gcodeSample)), chunk.Size)
}

// A directory has no bytes to answer with, and a module asking for them is
// told so rather than being handed whatever the provider does with a folder.
//
// It reads as the file that is not there, because a directory will not hand
// out bytes on the next call either, and a module told to come back asks for
// the same path for ever. The answer carries neither the path nor a reason,
// for the cause every other refusal here states.
func TestReadingADirectoryReadsAsAnAbsentFile(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	_, err := files.Read(t.Context(), storageapi.ReadParams{Storage: "bench", Path: "models"})
	require.ErrorIs(t, err, storageapi.ErrNoFile)
	require.NotErrorIs(t, err, storageapi.ErrUnreadable)
	require.NotContains(t, err.Error(), "models",
		"the answer names the path the module asked about")
}

// A path that climbs out of the storage is refused, in both spellings of a
// separator, and the refusal comes before anything opens a file. It reads as
// the file that is not there, because the storage contract joins absence and
// escape so that neither says which names in a store point out of it.
func TestAModuleCannotReadOutsideTheStorage(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	for _, path := range []string{
		"../part.gcode", `..\..\windows\win.ini`, "models/../../part.gcode", "../../../etc/passwd",
	} {
		_, err := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: path})
		require.ErrorIsf(t, err, storageapi.ErrNoFile, "%q was not refused by stat", path)

		_, err = files.Read(t.Context(), storageapi.ReadParams{Storage: "bench", Path: path})
		require.ErrorIsf(t, err, storageapi.ErrNoFile, "%q was not refused by read", path)
	}
}

// A storage this deployment does not declare and a file it does not hold are
// one refusal, down to the sentence, so a module cannot read the list of
// storages out of what it is refused.
func TestAnAbsentStorageAndAnAbsentFileAreOneRefusal(t *testing.T) {
	t.Parallel()

	files, graph := storageForModule(t, authz.ActionReadStorage)
	require.NoError(t, graph.Write(t.Context(),
		tuple(t, authz.TypeResourceKind, "storage", authz.RelViewer, readingModule)))

	_, absent := files.Stat(t.Context(), storageapi.StatParams{Storage: "shelf", Path: "part.gcode"})
	require.ErrorIs(t, absent, storageapi.ErrNoFile)

	_, missing := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: "nothing.gcode"})
	require.ErrorIs(t, missing, storageapi.ErrNoFile)

	_, climbing := files.Stat(t.Context(), storageapi.StatParams{Storage: "bench", Path: "../part.gcode"})
	require.ErrorIs(t, climbing, storageapi.ErrNoFile)

	require.Equal(t, missing.Error(), absent.Error(),
		"the sentence says whether the storage is one this deployment declares")
	require.Equal(t, missing.Error(), climbing.Error(),
		"the sentence says whether the path left the storage")
	require.NotContains(t, missing.Error(), "bench",
		"the refusal names the storage the module asked about")
}

