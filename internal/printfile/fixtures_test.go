// The fixtures in this file are built in Go. They are not slicer output, and
// nothing here should be read as proof that a real file looks like this. What a
// real PrusaSlicer file looks like is in testdata, and testdata/README.md says
// which version wrote it.
//
// They exist because PrusaSlicer renders a picture in its window and not on the
// command line, so no file this repository can produce from the command line
// carries a thumbnail to read back.

// fixtureLog is the part of testing this file needs, so a fixture can be built
// both in a test and while a fuzz corpus is being seeded.
type fixtureLog interface {
	Helper()
	Fatalf(format string, args ...any)
}

// fixturePNG encodes a plain PNG of the given size.
func fixturePNG(t fixtureLog, width, height int) []byte {
	t.Helper()

	img := image.NewNRGBA(image.Rect(0, 0, width, height))
	for y := range height {
		for x := range width {
			img.SetNRGBA(x, y, color.NRGBA{R: uint8(x), G: uint8(y), B: 0x80, A: 0xFF})
		}
	}

	var out bytes.Buffer
	if err := png.Encode(&out, img); err != nil {
		t.Fatalf("encode the fixture picture: %v", err)
	}

	return out.Bytes()
}

// fixtureQOI encodes a QOI picture of the given size. Every pixel is written as
// its own RGBA chunk, which is the simplest encoding the format allows.
func fixtureQOI(width, height int) []byte {
	var out bytes.Buffer

	out.WriteString("qoif")
	_ = binary.Write(&out, binary.BigEndian, uint32(width))
	_ = binary.Write(&out, binary.BigEndian, uint32(height))
	out.WriteByte(4)
	out.WriteByte(0)

	for y := range height {
		for x := range width {
			out.WriteByte(qoiOpRGBA)
			out.Write([]byte{uint8(x), uint8(y), 0x80, 0xFF})
		}
	}

	out.Write([]byte{0, 0, 0, 0, 0, 0, 0, 1})

	return out.Bytes()
}

// fixtureTextGCode writes a text G-code file: a picture block near the start,
// movement in the middle, and the settings at the end, which is the order
// PrusaSlicer writes them in.
func fixtureTextGCode(kind string, picture []byte, width, height, filler int) []byte {
	var out bytes.Buffer

	out.WriteString("; generated by a fixture\n")

	if picture != nil {
		encoded := base64.StdEncoding.EncodeToString(picture)

		fmt.Fprintf(&out, "; %s begin %dx%d %d\n", kind, width, height, len(picture))

		for start := 0; start < len(encoded); start += 78 {
			end := min(start+78, len(encoded))
			fmt.Fprintf(&out, "; %s\n", encoded[start:end])
		}

		fmt.Fprintf(&out, "; %s end\n", kind)
	}

	for i := range filler {
		fmt.Fprintf(&out, "G1 X%d Y%d E0.1\n", i%200, i%150)
	}

	out.WriteString("; filament used [mm] = 133.16\n")
	out.WriteString("; filament used [g] = 0.40\n")
	out.WriteString("; estimated printing time (normal mode) = 1h 2m 16s\n")
	out.WriteString("; layer_height = 0.3\n")
	out.WriteString("; nozzle_diameter = 0.4\n")
	out.WriteString("; filament_type = PLA\n")
	out.WriteString("; printer_model = MK4IS\n")

	return out.Bytes()
}

// bgcodeBlock is one block a binary fixture is built from.
type bgcodeBlock struct {
	kind        uint16
	compression uint16
	params      []byte
	data        []byte
}

// fixtureBGCode writes a binary container holding the given blocks, with a
// CRC-32 after each one, which is what PrusaSlicer writes.
func fixtureBGCode(t fixtureLog, blocks []bgcodeBlock) []byte {
	t.Helper()

	var out bytes.Buffer

	out.WriteString("GCDE")
	_ = binary.Write(&out, binary.LittleEndian, uint32(supportedVersion))
	_ = binary.Write(&out, binary.LittleEndian, uint16(checksumCRC32))

	for _, b := range blocks {
		body := b.data

		if b.compression == compressionDeflate {
			var packed bytes.Buffer

			writer := zlib.NewWriter(&packed)
			if _, err := writer.Write(b.data); err != nil {
				t.Fatalf("pack the fixture block: %v", err)
			}

			if err := writer.Close(); err != nil {
				t.Fatalf("close the fixture packer: %v", err)
			}

			body = packed.Bytes()
		}

		var header bytes.Buffer

		_ = binary.Write(&header, binary.LittleEndian, b.kind)
		_ = binary.Write(&header, binary.LittleEndian, b.compression)
		_ = binary.Write(&header, binary.LittleEndian, uint32(len(b.data)))

		if b.compression != compressionNone {
			_ = binary.Write(&header, binary.LittleEndian, uint32(len(body)))
		}

		header.Write(b.params)
		header.Write(body)

		out.Write(header.Bytes())
		_ = binary.Write(&out, binary.LittleEndian, crc32.ChecksumIEEE(header.Bytes()))
	}

	return out.Bytes()
}

// metadataParams is the encoding field every metadata block declares. Zero is
// the INI encoding, which is the only one the specification names.
func metadataParams() []byte { return []byte{0, 0} }

// thumbnailParams is a thumbnail block's format and size.
func thumbnailParams(format, width, height uint16) []byte {
	out := make([]byte, 6)
	binary.LittleEndian.PutUint16(out[0:2], format)
	binary.LittleEndian.PutUint16(out[2:4], width)
	binary.LittleEndian.PutUint16(out[4:6], height)

	return out
}

// fixtureProject writes a zip holding one named entry, which is the shape of a
// PrusaSlicer project as far as this package reads it.
func fixtureProject(t fixtureLog, name string, body []byte) []byte {
	t.Helper()

	var out bytes.Buffer

	archive := zip.NewWriter(&out)

	entry, err := archive.Create(name)
	if err != nil {
		t.Fatalf("create the fixture entry: %v", err)
	}

	if _, err = entry.Write(body); err != nil {
		t.Fatalf("write the fixture entry: %v", err)
	}

	if err = archive.Close(); err != nil {
		t.Fatalf("close the fixture archive: %v", err)
	}

	return out.Bytes()
}
