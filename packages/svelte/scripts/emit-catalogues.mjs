// The catalogues the library ships, from the files a translator edits.
//
// Three outputs. Only locales/en.errors.json is committed. The two
// catalogues.ts files are gitignored, and every script that reads them runs
// this first:
//
//   locales/en.errors.json   one `error.<code>` line per code in the fault
//                            registry, so every fault the core can answer has
//                            an English line and a translator has the whole
//                            list in one file
//   src/i18n/catalogues.ts   every locale file as one TypeScript module,
//                            without the setup wizard's lines
//   src/shell/setup-wizard/catalogues.ts
//                            the setup wizard's lines, which only its own
//                            chunk loads: a server draws the wizard once, and
//                            every page after it would carry them for nothing
//
// The two modules exist because the package ships its sources: `dist/` is
// written by transpiling `src/` file by file, and a JSON file imported from
// outside `src/` would have no path that holds in the published package, in
// the Vite build and in the declaration emit at once. Generating a module
// inside `src/` gives all three the same answer and costs one gate.
//
// `pnpm run catalogues` runs it, and `build`, `check:svelte`, `test` and
// `prepare` each call that first. `src/i18n/catalogues.test.ts` fails when a
// locale file changed and this did not run.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { format as prettify, resolveConfig } from 'prettier';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const REPOSITORY = fileURLToPath(new URL('../../..', import.meta.url));

export const LOCALES_DIR = join(ROOT, 'locales');
export const ERRORS_FILE = join(LOCALES_DIR, 'en.errors.json');
export const CATALOGUES_FILE = join(ROOT, 'src', 'i18n', 'catalogues.ts');
export const WIZARD_CATALOGUES_FILE = join(
  ROOT,
  'src',
  'shell',
  'setup-wizard',
  'catalogues.ts',
);

/** The prefix of every line the setup wizard's chunk carries. */
export const WIZARD_PREFIX = 'setupWizard.';
const REGISTRY_FILE = join(REPOSITORY, 'docs', 'errors', 'error-codes.json');

// `JSON.parse` answers `any`, which the typed lint rules refuse to let into a
// variable. Reading it through a signature that answers `unknown` makes every
// caller say what it expects, which is what typescript.md asks of a trust
// boundary anyway.
/** @type {(text: string) => unknown} */
const parseJson = JSON.parse;

const HEADER = [
  '// Generated by scripts/emit-catalogues.mjs from locales/*.json.',
  '// Do not edit: change the locale file and run `pnpm build`.',
].join('\n');

/**
 * The English line for every fault code the core can answer. The key is the
 * code: a screen renders a fault by its code and keeps the server's English
 * message beside it.
 *
 * @returns {Promise<Record<string, string>>}
 */
export const errorCatalogue = async () => {
  const registry =
    /** @type {{ codes: { code: string, summary: string, action?: string }[] }} */ (
      parseJson(await readFile(REGISTRY_FILE, 'utf8'))
    );
  /** @type {Record<string, string>} */
  const messages = {};

  for (const entry of registry.codes) {
    messages[`error.${entry.code}`] = entry.summary;
    if (entry.action !== undefined) {
      messages[`error.${entry.code}.action`] = entry.action;
    }
  }

  return messages;
};

/**
 * Every locale file, by its tag. A tag may have more than one file, and
 * `en.errors.json` is why. `_meta` keys are the translator's notes and never
 * reach a screen, so they are dropped here.
 *
 * @returns {Promise<Record<string, Record<string, string>>>}
 */
export const catalogues = async () => {
  const files = (await readdir(LOCALES_DIR))
    .filter((name) => name.endsWith('.json'))
    .sort();
  /** @type {Record<string, Record<string, string>>} */
  const byTag = {};

  for (const name of files) {
    const tag = name.slice(0, name.indexOf('.'));
    const parsed = /** @type {Record<string, string>} */ (
      parseJson(await readFile(join(LOCALES_DIR, name), 'utf8'))
    );
    const held = byTag[tag] ?? {};

    for (const [key, message] of Object.entries(parsed)) {
      if (!key.startsWith('_')) held[key] = message;
    }

    byTag[tag] = held;
  }

  return byTag;
};

/**
 * The maps of one module, each language holding the keys `keep` takes.
 *
 * @param {Record<string, Record<string, string>>} byTag
 * @param {(key: string) => boolean} keep
 * @returns {string}
 */
const bodyOf = (byTag, keep) =>
  Object.keys(byTag)
    .sort()
    .map((tag) => {
      const messages = byTag[tag] ?? {};
      const lines = Object.keys(messages)
        .filter(keep)
        .sort()
        .map(
          (key) =>
            `    ${JSON.stringify(key)}: ${JSON.stringify(messages[key])},`,
        );

      return [`  ${tag}: {`, ...lines, '  },'].join('\n');
    })
    .join('\n');

/**
 * The module `src/i18n/locale.svelte.ts` imports.
 *
 * @param {Record<string, Record<string, string>>} byTag
 * @returns {string}
 */
export const catalogueModule = (byTag) =>
  [
    HEADER,
    '',
    "import type { LocaleTag } from './locale.svelte';",
    "import type { Messages } from './messages';",
    '',
    "/** The library's own texts, one map per language. English is the source. */",
    'export const CORE_CATALOGUES: Partial<Record<LocaleTag, Messages>> = {',
    bodyOf(byTag, (key) => !key.startsWith(WIZARD_PREFIX)),
    '};',
    '',
  ].join('\n');

/**
 * The module the setup wizard's chunk imports, which adds its lines to the
 * core's catalogue when the wizard is drawn.
 *
 * @param {Record<string, Record<string, string>>} byTag
 * @returns {string}
 */
export const wizardCatalogueModule = (byTag) =>
  [
    HEADER,
    '',
    "import type { LocaleTag } from '../../i18n/locale.svelte';",
    "import type { Messages } from '../../i18n/messages';",
    '',
    "/** The setup wizard's texts, one map per language. English is the source. */",
    'export const WIZARD_CATALOGUES: Partial<Record<LocaleTag, Messages>> = {',
    bodyOf(byTag, (key) => key.startsWith(WIZARD_PREFIX)),
    '};',
    '',
  ].join('\n');

/**
 * The generated module as Prettier would write it, so `pnpm run format:check`
 * passes on a file no person edits.
 *
 * @param {string} source
 * @returns {Promise<string>}
 */
export const formatted = async (source) => {
  const options = await resolveConfig(CATALOGUES_FILE);

  return prettify(source, { ...options, filepath: CATALOGUES_FILE });
};

/** Writes every output. @returns {Promise<void>} */
export const emitCatalogues = async () => {
  const errors = await errorCatalogue();
  await writeFile(ERRORS_FILE, `${JSON.stringify(errors, null, 2)}\n`, 'utf8');
  const byTag = await catalogues();
  await writeFile(
    CATALOGUES_FILE,
    await formatted(catalogueModule(byTag)),
    'utf8',
  );
  await writeFile(
    WIZARD_CATALOGUES_FILE,
    await formatted(wizardCatalogueModule(byTag)),
    'utf8',
  );
};

const invoked = process.argv[1];
if (invoked !== undefined && import.meta.url === pathToFileURL(invoked).href) {
  await emitCatalogues();
}
